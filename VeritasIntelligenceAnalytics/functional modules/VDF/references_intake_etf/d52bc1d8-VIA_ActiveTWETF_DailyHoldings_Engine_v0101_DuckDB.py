def def_clean_text(value: Any) -> str:
    if def_is_missing(
        value
    ):
        return ""

    return re.sub(
        r"\s+",
        " ",
        str(value).replace(
            "\xa0",
            " ",
        ),
    ).strip()


def def_parse_float(
    value: Any,
) -> Optional[float]:
    text = def_clean_text(
        value
    )

    if not text:
        return None

    negative_parentheses = (
        text.startswith("(")
        and text.endswith(")")
    )
    text = (
        text.replace(
            ",",
            "",
        )
        .replace(
            "，",
            "",
        )
        .replace(
            "%",
            "",
        )
        .strip()
    )

    match = re.search(
        r"-?\d+(?:\.\d+)?",
        text,
    )

    if not match:
        return None

    try:
        parsed = float(
            match.group(0)
        )
    except ValueError:
        return None

    if not math.isfinite(
        parsed
    ):
        return None

    return (
        -abs(
            parsed
        )
        if negative_parentheses
        else parsed
    )


def def_extract_stock_identity(
    value: str,
) -> Tuple[str, str, str]:
    text = def_clean_text(
        value
    )

    match = re.search(
        r"([0-9]{4}[A-Z]?)\.(TW|TWO)",
        text,
        flags=re.IGNORECASE,
    )

    if match:
        raw = match.group(
            1
        ).upper()

        suffix = match.group(
            2
        ).upper()

        name = re.sub(
            r"\(?[0-9]{4}[A-Z]?\.(?:TW|TWO)\)?",
            "",
            text,
            flags=re.IGNORECASE,
        ).strip()

        return (
            raw,
            f"{raw}.{suffix}",
            name,
        )

    if re.search(
        r"\.(?:TF|TFE)\b|(?:期貨|選擇權)",
        text,
        flags=re.IGNORECASE,
    ):
        return (
            "",
            "",
            text,
        )

    match = re.search(
        r"^\s*([0-9]{4}[A-Z]?)\b",
        text,
    )

    if match:
        raw = match.group(
            1
        ).upper()

        name = re.sub(
            rf"\b{re.escape(raw)}\b",
            "",
            text,
        ).strip(
            " -()"
        )

        return (
            raw,
            f"{raw}.TW",
            name,
        )

    return (
        "",
        "",
        text,
    )


def def_parse_portfolio_date_value(
    value: Any,
) -> Optional[date]:
    text = def_clean_text(
        value
    )

    if not text:
        return None

    text = (
        text.replace("年", "/")
        .replace("月", "/")
        .replace("日", "")
        .replace(".", "/")
        .replace("-", "/")
    )
    match = re.fullmatch(
        r"(\d{2,4})/(\d{1,2})/(\d{1,2})",
        text,
    )

    if not match:
        return None

    year, month, day_value = (
        int(part)
        for part in match.groups()
    )

    if year < 1911:
        year += 1911

    try:
        return date(
            year,
            month,
            day_value,
        )
    except ValueError:
        return None


def def_html_to_text(
    html: str,
) -> str:
    if BeautifulSoup is not None:
        return BeautifulSoup(
            html,
            "html.parser",
        ).get_text(
            " ",
            strip=True,
        )

    return def_clean_text(
        re.sub(
            r"<[^>]+>",
            " ",
            html,
        )
    )


def def_extract_portfolio_date(
    html: str,
) -> str:
    text = def_html_to_text(
        html
    )

    patterns = (
        r"(?:資料|持股|投資組合|淨值)?日期[:：]?\s*((?:20\d{2}|\d{2,3})[年./-]\d{1,2}[月./-]\d{1,2}日?)",
        r"((?:20\d{2})[年./-]\d{1,2}[月./-]\d{1,2}日?)",
        r"((?:1\d{2})[年./-]\d{1,2}[月./-]\d{1,2}日?)",
    )

    for pattern in patterns:
        for match in re.finditer(
            pattern,
            text,
        ):
            parsed = def_parse_portfolio_date_value(
                match.group(1)
            )
            if parsed is not None:
                return parsed.strftime(
                    DATE_OUTPUT_FORMAT
                )

    return ""


