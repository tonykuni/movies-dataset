def def_register_universe_snapshot(
    con: Any,
    universe: Dict[str, Dict[str, str]],
    universe_source: str,
) -> None:
    snapshot_at = def_now_taipei()
    rows = [
        {
            "snapshot_at": snapshot_at,
            "etf_ticker": ticker,
            "etf_name": meta[
                "name"
            ],
            "issuer": meta[
                "issuer"
            ],
            "universe_source": universe_source,
        }
        for ticker, meta in sorted(
            universe.items()
        )
    ]

    df = pd.DataFrame(
        rows
    )

    con.register(
        "universe_stage",
        df,
    )

    try:
        con.execute(
            "BEGIN TRANSACTION"
        )
        con.execute(
            """
            DELETE FROM active_tw_etf_universe
            USING universe_stage s
            WHERE active_tw_etf_universe.etf_ticker = s.etf_ticker
              AND CAST(active_tw_etf_universe.snapshot_at AS DATE)
                  = CAST(s.snapshot_at AS DATE)
            """
        )
        con.execute(
            """
            INSERT INTO active_tw_etf_universe
            SELECT
                snapshot_at,
                etf_ticker,
                etf_name,
                issuer,
                universe_source
            FROM universe_stage
            """
        )
        con.execute(
            "COMMIT"
        )
    except Exception:
        con.execute(
            "ROLLBACK"
        )
        raise
    finally:
        con.unregister(
            "universe_stage"
        )


def def_upsert_holdings(
    con: Any,
    latest: pd.DataFrame,
) -> None:
    if latest.empty:
        return

    stage = latest.copy()

    stage[
        "portfolio_date"
    ] = pd.to_datetime(
        stage[
            "portfolio_date"
        ],
        errors="coerce",
    ).dt.date

    stage[
        "fetched_at"
    ] = pd.to_datetime(
        stage[
            "fetched_at"
        ],
        errors="coerce",
    )

    if stage[
        "portfolio_date"
    ].isna().any():
        raise RuntimeError(
            "UPSERT_PORTFOLIO_DATE_INVALID"
        )

    if stage.duplicated(
        subset=[
            "portfolio_date",
            "etf_ticker",
            "holding_ticker",
        ]
    ).any():
        raise RuntimeError(
            "UPSERT_DUPLICATE_NATURAL_KEY"
        )

    con.register(
        "holdings_stage",
        stage,
    )

    try:
        con.execute(
            "BEGIN TRANSACTION"
        )
        # Replace the complete ETF/date snapshot. Deleting only overlapping
        # holding keys would leave stale rows after an intra-day correction.
        con.execute(
            """
            DELETE FROM holdings_daily
            USING (
                SELECT DISTINCT
                    portfolio_date,
                    etf_ticker
                FROM holdings_stage
            ) s
            WHERE holdings_daily.portfolio_date = s.portfolio_date
              AND holdings_daily.etf_ticker = s.etf_ticker
            """
        )

        con.execute(
            """
            INSERT INTO holdings_daily
            SELECT
                portfolio_date,
                etf_ticker,
                etf_yf_ticker,
                etf_name,
                issuer,
                holding_ticker,
                holding_yf_ticker,
                holding_name,
                weight_pct,
                shares,
                source_type,
                source_url,
                fetched_at
            FROM holdings_stage
            """
        )
        con.execute(
            "COMMIT"
        )
    except Exception:
        con.execute(
            "ROLLBACK"
        )
        raise
    finally:
        con.unregister(
            "holdings_stage"
        )


