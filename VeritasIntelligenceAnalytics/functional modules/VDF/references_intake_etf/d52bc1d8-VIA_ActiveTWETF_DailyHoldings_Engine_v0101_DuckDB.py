def def_dependency_status() -> Dict[str, Any]:
    components = {
        "pandas": pd is not None,
        "duckdb": duckdb is not None,
        "requests": requests is not None,
        "beautifulsoup4": BeautifulSoup is not None,
        "html_parser_backend": any(
            importlib.util.find_spec(name) is not None
            for name in ("lxml", "html5lib")
        ),
    }

    offline_required = (
        "pandas",
        "duckdb",
    )
    live_required = (
        "pandas",
        "duckdb",
        "requests",
        "beautifulsoup4",
        "html_parser_backend",
    )

    return {
        "components": components,
        "offline_ready": all(
            components[name]
            for name in offline_required
        ),
        "live_ready": all(
            components[name]
            for name in live_required
        ),
        "offline_missing": [
            name
            for name in offline_required
            if not components[name]
        ],
        "live_missing": [
            name
            for name in live_required
            if not components[name]
        ],
    }


def def_require_dependencies(
    live_fetch: bool,
) -> None:
    status = def_dependency_status()
    ready_key = (
        "live_ready"
        if live_fetch
        else "offline_ready"
    )
    missing_key = (
        "live_missing"
        if live_fetch
        else "offline_missing"
    )

    if not status[ready_key]:
        raise RuntimeError(
            "DEPENDENCIES_MISSING:"
            + ",".join(
                status[missing_key]
            )
            + "; install pandas duckdb requests beautifulsoup4 lxml"
        )


