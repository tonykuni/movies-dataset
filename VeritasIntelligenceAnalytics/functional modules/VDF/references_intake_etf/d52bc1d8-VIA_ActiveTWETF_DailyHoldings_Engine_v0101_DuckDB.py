def def_rebuild_latest_changes(
    con: Any,
) -> int:
    con.execute(
        "DELETE FROM holdings_changes"
    )

    con.execute(
        f"""
        INSERT INTO holdings_changes
        WITH dates AS (
            SELECT
                etf_ticker,
                portfolio_date,
                DENSE_RANK() OVER (
                    PARTITION BY etf_ticker
                    ORDER BY portfolio_date DESC
                ) AS date_rank
            FROM (
                SELECT DISTINCT
                    etf_ticker,
                    portfolio_date
                FROM holdings_daily
            )
        ),
        date_pairs AS (
            SELECT
                etf_ticker,
                MAX(
                    CASE
                        WHEN date_rank = 1 THEN portfolio_date
                    END
                ) AS latest_date,
                MAX(
                    CASE
                        WHEN date_rank = 2 THEN portfolio_date
                    END
                ) AS previous_date
            FROM dates
            WHERE date_rank <= 2
            GROUP BY etf_ticker
            HAVING previous_date IS NOT NULL
        ),
        latest AS (
            SELECT h.*
            FROM holdings_daily h
            JOIN date_pairs d
              ON h.etf_ticker = d.etf_ticker
             AND h.portfolio_date = d.latest_date
        ),
        previous AS (
            SELECT h.*
            FROM holdings_daily h
            JOIN date_pairs d
              ON h.etf_ticker = d.etf_ticker
             AND h.portfolio_date = d.previous_date
        ),
        joined AS (
            SELECT
                d.latest_date AS portfolio_date,
                d.previous_date AS previous_date,
                COALESCE(l.etf_ticker, p.etf_ticker) AS etf_ticker,
                COALESCE(l.holding_ticker, p.holding_ticker) AS holding_ticker,
                COALESCE(l.holding_name, p.holding_name) AS holding_name,
                p.holding_ticker IS NOT NULL AS previous_exists,
                l.holding_ticker IS NOT NULL AS current_exists,
                p.shares AS shares_previous,
                l.shares AS shares_current,
                p.weight_pct AS weight_previous,
                l.weight_pct AS weight_current
            FROM latest l
            FULL OUTER JOIN previous p
              ON l.etf_ticker = p.etf_ticker
             AND l.holding_ticker = p.holding_ticker
            JOIN date_pairs d
              ON d.etf_ticker = COALESCE(l.etf_ticker, p.etf_ticker)
        )
        SELECT
            portfolio_date,
            previous_date,
            etf_ticker,
            holding_ticker,
            holding_name,
            CASE
                WHEN NOT previous_exists THEN 'ADDED'
                WHEN NOT current_exists THEN 'REMOVED'
                WHEN shares_previous IS NOT NULL
                 AND shares_current IS NOT NULL
                 AND shares_current > shares_previous
                    THEN 'INCREASED'
                WHEN shares_previous IS NOT NULL
                 AND shares_current IS NOT NULL
                 AND shares_current < shares_previous
                    THEN 'DECREASED'
                ELSE 'WEIGHT_CHANGED'
            END AS change_type,
            shares_previous,
            shares_current,
            COALESCE(shares_current, 0) - COALESCE(shares_previous, 0)
                AS shares_change,
            weight_previous,
            weight_current,
            COALESCE(weight_current, 0) - COALESCE(weight_previous, 0)
                AS weight_change
        FROM joined
        WHERE
            previous_exists <> current_exists
            OR shares_previous IS DISTINCT FROM shares_current
            OR ABS(
                COALESCE(weight_current, 0)
                - COALESCE(weight_previous, 0)
            ) > {WEIGHT_CHANGE_EPSILON}
        """
    )

    return int(
        con.execute(
            "SELECT COUNT(*) FROM holdings_changes"
        ).fetchone()[0]
    )


