def def_atomic_copy_query_to_parquet(
    con: Any,
    query: str,
    target: Path,
) -> None:
    target = Path(
        target
    )
    target.parent.mkdir(
        parents=True,
        exist_ok=True,
    )
    temporary = target.with_name(
        target.name
        + f".tmp-{os.getpid()}"
    )

    if temporary.exists():
        temporary.unlink()

    escaped_temporary = str(
        temporary
    ).replace(
        "'",
        "''",
    )

    try:
        con.execute(
            f"""
            COPY (
                {query}
            )
            TO '{escaped_temporary}'
            (
                FORMAT PARQUET,
                COMPRESSION ZSTD
            )
            """
        )
        os.replace(
            temporary,
            target,
        )
    finally:
        if temporary.exists():
            temporary.unlink()


