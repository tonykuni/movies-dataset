def def_build_session() -> Any:
    def_require_dependencies(
        live_fetch=True
    )

    session = requests.Session()

    retry = Retry(
        total=HTTP_RETRY_TOTAL,
        connect=HTTP_RETRY_TOTAL,
        read=HTTP_RETRY_TOTAL,
        backoff_factor=HTTP_BACKOFF_FACTOR,
        status_forcelist=(429, 500, 502, 503, 504),
        allowed_methods=frozenset(("GET", "HEAD")),
        raise_on_status=False,
    )

    adapter = HTTPAdapter(
        max_retries=retry,
        pool_connections=8,
        pool_maxsize=8,
    )

    session.mount("https://", adapter)
    session.mount("http://", adapter)

    session.headers.update(
        {
            "User-Agent": USER_AGENT,
            "Accept-Language": "zh-TW,zh;q=0.9,en;q=0.7",
        }
    )

    return session


def def_http_get_text(
    session: Any,
    url: str,
) -> str:
    response = session.get(
        url,
        timeout=HTTP_TIMEOUT,
    )
    response.raise_for_status()

    header_encoding = ""
    content_type = response.headers.get(
        "Content-Type",
        "",
    )
    header_match = re.search(
        r"charset\s*=\s*([^;\s]+)",
        content_type,
        flags=re.IGNORECASE,
    )
    if header_match:
        header_encoding = header_match.group(
            1
        ).strip(
            "\"'"
        )

    meta_encoding = ""
    meta_match = re.search(
        br"charset\s*=\s*[\"']?([^\"'\s/>;]+)",
        response.content[
            :8192
        ],
        flags=re.IGNORECASE,
    )
    if meta_match:
        meta_encoding = meta_match.group(
            1
        ).decode(
            "ascii",
            errors="ignore",
        )

    candidates = [
        header_encoding,
        meta_encoding,
        (
            response.encoding
            if response.encoding
            and response.encoding.lower()
            != "iso-8859-1"
            else ""
        ),
        DEFAULT_HTTP_ENCODING,
        response.apparent_encoding or "",
    ]
    text = ""
    decode_errors: List[str] = []

    for encoding in dict.fromkeys(
        candidate
        for candidate in candidates
        if candidate
    ):
        try:
            text = response.content.decode(
                encoding,
            )
            break
        except (
            LookupError,
            UnicodeDecodeError,
        ) as exc:
            decode_errors.append(
                f"{encoding}:{exc}"
            )

    if not text:
        raise RuntimeError(
            "HTTP_DECODE_FAILED:"
            + " | ".join(
                decode_errors
            )
        )

    if not text.strip():
        raise RuntimeError(
            "HTTP_EMPTY_RESPONSE"
        )

    return text


