def def_parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "VIA Active Taiwan ETF "
            f"Daily Holdings Engine v{ENGINE_VERSION} DuckDB"
        )
    )

    parser.add_argument(
        "--version",
        action="version",
        version=(
            f"{ENGINE_NAME} {ENGINE_VERSION} ({ENGINE_BUILD})"
        ),
    )

    parser.add_argument(
        "--output-dir",
        default=str(
            DEFAULT_HOLDINGS_DIR
        ),
    )

    parser.add_argument(
        "--universe-csv",
        default=str(
            DEFAULT_UNIVERSE_CSV
        ),
    )

    parser.add_argument(
        "--duckdb-path",
        default=str(
            DEFAULT_DUCKDB_PATH
        ),
    )

    parser.add_argument(
        "--parquet-root",
        default=str(
            DEFAULT_PARQUET_ROOT
        ),
    )

    parser.add_argument(
        "--tickers",
        nargs="+",
        default=None,
    )

    parser.add_argument(
        "--self-test",
        action="store_true",
    )

    parser.add_argument(
        "--no-refresh-universe",
        action="store_true",
        help=(
            "Skip the TWSE official active-ETF list refresh and use the local SSOT."
        ),
    )

    parser.add_argument(
        "--check-dependencies",
        action="store_true",
    )

    parser.add_argument(
        "--verbose",
        action="store_true",
    )

    return parser.parse_args()


def def_main() -> int:
    args = def_parse_args()

    def_setup_logging(
        args.verbose
    )

    if args.check_dependencies:
        status = def_dependency_status()
        print(
            json.dumps(
                status,
                ensure_ascii=False,
                indent=2,
            )
        )
        return (
            0
            if status[
                "live_ready"
            ]
            else 4
        )

    if args.self_test:
        try:
            result = def_self_test(
                Path(
                    args.output_dir
                )
                / "_self_test"
            )
        except Exception as exc:
            logging.exception(
                "SELF_TEST_FAIL_CLOSED: %s",
                exc,
            )
            result = {
                "engine_version": ENGINE_VERSION,
                "engine_build": ENGINE_BUILD,
                "all_pass": False,
                "unexpected_exception": (
                    f"{type(exc).__name__}:{exc}"
                ),
            }

        print(
            json.dumps(
                result,
                ensure_ascii=False,
                indent=2,
            )
        )

        return (
            0
            if result[
                "all_pass"
            ]
            else 3
        )

    try:
        manifest = (
            def_fetch_daily_holdings(
                output_dir=Path(
                    args.output_dir
                ),
                universe_csv=Path(
                    args.universe_csv
                ),
                duckdb_path=Path(
                    args.duckdb_path
                ),
                parquet_root=Path(
                    args.parquet_root
                ),
                tickers=args.tickers,
                refresh_universe=(
                    not args.no_refresh_universe
                ),
            )
        )

        print(
            json.dumps(
                manifest,
                ensure_ascii=False,
                indent=2,
            )
        )

        return (
            0
            if manifest[
                "status"
            ]
            in (
                "PASS",
                "PARTIAL",
            )
            else 2
        )

    except Exception as exc:
        logging.exception(
            "FAIL_CLOSED: %s",
            exc,
        )

        return 2


