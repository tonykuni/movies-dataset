        f"  files found        : {summary['manifest_totals']['found']}/{summary['manifest_totals']['expected']}",
        f"  extra files        : {summary['manifest_totals']['extra']}",
        f"  total size         : {summary['manifest_totals']['size_total']:,} bytes",
