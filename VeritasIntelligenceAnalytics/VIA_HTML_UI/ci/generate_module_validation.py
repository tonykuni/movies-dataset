#!/usr/bin/env python3
"""Generate deterministic validation scripts from VIA Spec Extractor IR.

The generated Python validator is dependency-free and suitable for CI. A browser
smoke-test payload is emitted separately for a real file:// page or DevTools.
"""
from __future__ import annotations

import argparse
import json
import re
import textwrap
from pathlib import Path

DEFAULT_IDS = [
    "templateSelect", "templateMode", "applyTemplate", "exportTemplate",
    "addModule", "addChart", "applyPivot", "exportExcel", "exportExcel2",
    "jsonPreview", "loadState", "clearState",
]
DEFAULT_TOKENS = [
    "localStorage", "BroadcastChannel", "SpreadsheetML", "PivotSummary",
    "modules", "charts", "history", "version",
]


def slugify(value: str) -> str:
    value = re.sub(r"[^a-zA-Z0-9]+", "-", value.strip().lower()).strip("-")
    return value or "via-module"


def load_profile(path: Path | None, industry: str) -> dict:
    if not path:
        return {"name": industry or "VIA Industry", "modules": [], "charts": []}
    data = json.loads(path.read_text(encoding="utf-8"))
    profile = data.get(industry, data) if isinstance(data, dict) else {}
    if not isinstance(profile, dict):
        raise ValueError(f"profile {industry!r} is not an object")
    return profile


def item_ids(ir: dict) -> list[str]:
    values = []
    for item in ir.get("items", []):
        attrs = item.get("attrs") or {}
        ident = attrs.get("id")
        if ident and ident not in values:
            values.append(str(ident))
    return values


def build_manifest(ir: dict, profile: dict, industry: str, html_path: Path) -> dict:
    modules = profile.get("modules") or []
    charts = profile.get("charts") or []
    module_names = [str(m.get("name")) for m in modules if m.get("name")]
    chart_names = [str(c.get("name")) for c in charts if c.get("name")]
    return {
        "contract": "VIA_MODULE_VALIDATION/1.0",
        "industry": industry,
        "profile_name": profile.get("name", industry),
        "html": str(html_path),
        "required_dom_ids": DEFAULT_IDS,
        "required_tokens": DEFAULT_TOKENS,
        "required_labels": [profile.get("name", industry), *module_names, *chart_names],
        "ir": {
            "contract": ir.get("contract", ""),
            "version": ir.get("version", ""),
            "min_items": max(1, len(ir.get("items", []))),
            "min_ui_items": sum(1 for x in ir.get("items", []) if x.get("kind") == "UI"),
            "observed_ids": item_ids(ir),
        },
    }


def render_validator(manifest: dict) -> str:
    payload = json.dumps(manifest, ensure_ascii=False, indent=2)
    return f'''#!/usr/bin/env python3
"""Generated by VIA Spec Extractor → module validation generator."""
from __future__ import annotations
import argparse, json, re, sys
from pathlib import Path

MANIFEST = {payload}


def check(condition, message, failures):
    if not condition:
        failures.append(message)


def main():
    ap = argparse.ArgumentParser(description="Validate a VIA industry module surface")
    ap.add_argument("--html", default=MANIFEST["html"])
    ap.add_argument("--ir", default="")
    ap.add_argument("--report", default="via-module-validation-report.json")
    args = ap.parse_args()
    html_path = Path(args.html)
    failures = []
    if not html_path.is_file():
        failures.append(f"HTML not found: {{html_path}}")
        print("FAIL")
        return 1
    html = html_path.read_text(encoding="utf-8", errors="replace")
    for ident in MANIFEST["required_dom_ids"]:
        check(re.search(r'id=["\\\']' + re.escape(ident) + r'["\\\']', html) is not None,
              f"missing DOM id: {{ident}}", failures)
    for token in MANIFEST["required_tokens"]:
        check(token in html, f"missing runtime token: {{token}}", failures)
    for label in MANIFEST["required_labels"]:
        check(label in html, f"missing industry label: {{label}}", failures)
    if args.ir:
        ir_path = Path(args.ir)
        if not ir_path.is_file():
            failures.append(f"IR not found: {{ir_path}}")
        else:
            ir = json.loads(ir_path.read_text(encoding="utf-8"))
            check(len(ir.get("items", [])) >= MANIFEST["ir"]["min_items"], "IR item count regressed", failures)
            check(sum(1 for x in ir.get("items", []) if x.get("kind") == "UI") >= MANIFEST["ir"]["min_ui_items"], "IR UI item count regressed", failures)
            if MANIFEST["ir"]["contract"]:
                check(ir.get("contract") == MANIFEST["ir"]["contract"], "IR contract changed", failures)
    report = {{"ok": not failures, "industry": MANIFEST["industry"], "html": str(html_path), "failures": failures}}
    Path(args.report).write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    if failures:
        print("FAIL")
        for failure in failures:
            print(" -", failure)
        return 1
    print("PASS: VIA industry surface validated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
'''


def render_browser_smoke(manifest: dict) -> str:
    data = json.dumps(manifest, ensure_ascii=False, indent=2)
    return f'''/* Generated VIA browser smoke test. Paste into DevTools on the target file:// page. */
(()=>{{
  const manifest={data}; const failures=[]; const q=s=>document.querySelector(s);
  const check=(ok,msg)=>{{if(!ok) failures.push(msg)}};
  manifest.required_dom_ids.forEach(id=>check(!!document.getElementById(id),`missing DOM id: ${{id}}`));
  manifest.required_labels.forEach(label=>check(document.body.innerText.includes(label),`missing label: ${{label}}`));
  const template=q('#templateSelect');
  if(template && [...template.options].some(o=>o.value===manifest.industry)){{
    template.value=manifest.industry;
    q('#applyTemplate')?.click();
  }}
  const state=JSON.parse(localStorage.getItem('via.sync.state.v2')||'null');
  check(!!state, 'missing v2 local state after template action');
  check(!!state?.analytics, 'missing analytics state');
  check(Array.isArray(state?.modules), 'missing modules array');
  check(Array.isArray(state?.analytics?.charts), 'missing charts array');
  const result={{ok:!failures.length, failures, industry:manifest.industry, modules:state?.modules?.length||0, charts:state?.analytics?.charts?.length||0}};
  console.log('VIA_MODULE_VALIDATION',result); return result;
}})();
'''


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--ir", required=True, help="VIA Spec Extractor via_spec_ir.json")
    ap.add_argument("--html", required=True, help="target standalone HTML")
    ap.add_argument("--profile", default="", help="industry-profile.json")
    ap.add_argument("--industry", required=True, help="profile key, e.g. smart-manufacturing")
    ap.add_argument("--out", required=True, help="output directory")
    args = ap.parse_args()
    ir_path, html_path, out = Path(args.ir), Path(args.html), Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    ir = json.loads(ir_path.read_text(encoding="utf-8"))
    profile = load_profile(Path(args.profile) if args.profile else None, args.industry)
    manifest = build_manifest(ir, profile, args.industry, html_path)
    slug = slugify(args.industry)
    (out / f"validate_{slug}.manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    (out / f"validate_{slug}.py").write_text(render_validator(manifest), encoding="utf-8")
    (out / f"validate_{slug}.browser.js").write_text(render_browser_smoke(manifest), encoding="utf-8")
    print(json.dumps({"out": str(out), "validator": f"validate_{slug}.py", "browser": f"validate_{slug}.browser.js", "labels": len(manifest["required_labels"])}, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
