#requires -Version 7.0
<#
Invoke-VCGC-Boot-v0100 — 單行薄殼(零業務邏輯):叫 VCGC_StartupEngine 尾版的動詞(預設 boot)
  boot = 先降壓 → 三道獨立子行程(環境 / 備份 · Graphify / MCP / OmniRoute 探測 / VDF · 遠端控制狀態)→ 一行就緒摘要
  其他動詞照傳:audit · backup · remote · scan · lanes · status …(全部邏輯與加速器都在 Python)
用法:& "$HOME\OneDrive\Documents\movies-dataset\VeritasIntelligenceAnalytics\Invoke-VCGC-Boot-v0100.ps1" [動詞] [參數…]
