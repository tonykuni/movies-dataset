def def_export_holdings_parquet(
    con: Any,
    parquet_root: Path,
) -> int:
    """
    Export one canonical parquet file per portfolio_date.
    Re-running a date overwrites that day's file, avoiding duplicates.
    """
    parquet_root = Path(
        parquet_root
    )

    parquet_root.mkdir(
        parents=True,
        exist_ok=True,
    )

    dates = [
        row[0]
        for row in con.execute(
            """
            SELECT DISTINCT portfolio_date
            FROM holdings_daily
            WHERE portfolio_date IS NOT NULL
            ORDER BY portfolio_date
            """
        ).fetchall()
    ]

    written = 0

    for portfolio_date in dates:
        date_text = str(
            portfolio_date
        )

        folder = (
            parquet_root
            / "holdings_daily"
            / f"portfolio_date={date_text}"
        )

        folder.mkdir(
            parents=True,
            exist_ok=True,
        )

        target = (
            folder
            / "part-00000.parquet"
        )

        escaped_target = str(
            target
        ).replace(
            "'",
            "''",
        )

        con.execute(
            f"""
            COPY (
                SELECT
                    portfolio_date,
                    etf_ticker,
                    etf_yf_ticker,
                    etf_name,
                    issuer,
                    holding_ticker,
                    holding_yf_ticker,
                    holding_name,
                    weight_pct,
                    shares,
                    source_type,
                    source_url,
                    fetched_at
                FROM holdings_daily
                WHERE portfolio_date = DATE '{date_text}'
                ORDER BY etf_ticker, holding_ticker
            )
            TO '{escaped_target}'
            (
                FORMAT PARQUET,
                COMPRESSION ZSTD
            )
            """
        )

        written += 1

    return written


def def_export_reference_parquets(
    con: Any,
    parquet_root: Path,
) -> None:
    parquet_root = Path(
        parquet_root
    )

    parquet_root.mkdir(
        parents=True,
        exist_ok=True,
    )

    exports = {
        "universe_latest.parquet": """
            WITH ranked AS (
                SELECT *,
                    ROW_NUMBER() OVER (
                        PARTITION BY etf_ticker
                        ORDER BY snapshot_at DESC
                    ) AS rn
                FROM active_tw_etf_universe
            )
            SELECT
                snapshot_at,
                etf_ticker,
                etf_name,
                issuer,
                universe_source
            FROM ranked
            WHERE rn = 1
            ORDER BY etf_ticker
        """,
        "fetch_status_latest.parquet": """
            WITH ranked AS (
                SELECT *,
                    ROW_NUMBER() OVER (
                        PARTITION BY etf_ticker
                        ORDER BY run_at DESC
                    ) AS rn
                FROM fetch_status
            )
            SELECT
                run_at,
                etf_ticker,
                status,
                source_type,
                holding_count,
                portfolio_date,
                errors
            FROM ranked
            WHERE rn = 1
            ORDER BY etf_ticker
        """,
        "holdings_changes_latest.parquet": """
            SELECT *
            FROM holdings_changes
            ORDER BY etf_ticker, holding_ticker
        """,
    }

    for filename, query in exports.items():
        target = (
            parquet_root
            / filename
        )

        escaped_target = str(
            target
        ).replace(
            "'",
            "''",
        )

        con.execute(
            f"""
            COPY (
                {query}
            )
            TO '{escaped_target}'
            (
                FORMAT PARQUET,
                COMPRESSION ZSTD
            )
            """
        )


