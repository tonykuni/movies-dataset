def def_load_dynamic_universe(
    universe_csv: Path,
) -> Tuple[Dict[str, Dict[str, str]], str]:
    """
    Priority:
    1. ActiveTWETF_Latest.csv from SSOT updater.
    2. Embedded bootstrap universe.

    Expected SSOT columns:
        raw_ticker, name
    Optional:
        issuer
    """
    universe_csv = Path(
        universe_csv
    )

    if universe_csv.exists():
        df = pd.read_csv(
            universe_csv,
            dtype=str,
            encoding=CSV_ENCODING,
        )

        required = {
            "raw_ticker",
            "name",
        }

        missing = (
            required
            - set(
                df.columns
            )
        )

        if missing:
            raise RuntimeError(
                "UNIVERSE_SSOT_COLUMNS_MISSING:"
                + ",".join(
                    sorted(
                        missing
                    )
                )
            )

        result: Dict[
            str,
            Dict[str, str]
        ] = {}

        for row in df.to_dict(
            "records"
        ):
            ticker = (
                str(
                    row.get(
                        "raw_ticker",
                        "",
                    )
                )
                .strip()
                .upper()
            )

            if not re.fullmatch(
                r"00\d{3}A",
                ticker,
            ):
                continue

            name = str(
                row.get(
                    "name",
                    "",
                )
            ).strip()

            issuer = str(
                row.get(
                    "issuer",
                    "",
                )
                or ""
            ).strip()

            if not issuer:
                issuer = (
                    def_guess_issuer_from_name(
                        name
                    )
                )

            result[
                ticker
            ] = {
                "name": name,
                "issuer": issuer,
            }

        if not result:
            raise RuntimeError(
                "UNIVERSE_SSOT_ZERO_VALID_ROWS"
            )

        return (
            result,
            "ACTIVE_TW_ETF_SSOT_CSV",
        )

    return (
        dict(
            BOOTSTRAP_ACTIVE_TW_ETF_UNIVERSE
        ),
        "BOOTSTRAP_FALLBACK",
    )


