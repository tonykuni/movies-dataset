def def_fetch_daily_holdings(
    output_dir: Path = DEFAULT_HOLDINGS_DIR,
    universe_csv: Path = DEFAULT_UNIVERSE_CSV,
    duckdb_path: Path = DEFAULT_DUCKDB_PATH,
    parquet_root: Path = DEFAULT_PARQUET_ROOT,
    tickers: Optional[
        Iterable[str]
    ] = None,
) -> Dict[str, Any]:
    output_dir = Path(
        output_dir
    )

    output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    universe, universe_source = (
        def_load_dynamic_universe(
            universe_csv
        )
    )

    selected = (
        [
            str(
                ticker
            )
            .strip()
            .upper()
            for ticker in tickers
        ]
        if tickers
        else sorted(
            universe
        )
    )

    session = def_build_session()

    holding_frames: List[
        pd.DataFrame
    ] = []

    status_rows: List[
        Dict[str, Any]
    ] = []

    for ticker in selected:
        meta = universe.get(
            ticker
        )

        if meta is None:
            status_rows.append(
                {
                    "etf_ticker": ticker,
                    "status": "FAIL",
                    "source_type": "",
                    "holding_count": 0,
                    "portfolio_date": "",
                    "errors": "TICKER_NOT_IN_DYNAMIC_UNIVERSE",
                }
            )
            continue

        logging.info(
            "Fetch %s %s",
            ticker,
            meta[
                "name"
            ],
        )

        frame, status = (
            def_fetch_one_etf(
                session=session,
                etf_ticker=ticker,
                meta=meta,
            )
        )

        status_rows.append(
            status
        )

        if not frame.empty:
            holding_frames.append(
                frame
            )

        time.sleep(
            REQUEST_SLEEP_SECONDS
        )

    latest = (
        pd.concat(
            holding_frames,
            ignore_index=True,
        )
        if holding_frames
        else pd.DataFrame(
            columns=HOLDING_COLUMNS
        )
    )

    latest = def_normalize_holdings(
        latest
    )

    status_df = pd.DataFrame(
        status_rows
    )

    con = def_open_duckdb(
        duckdb_path
    )

    try:
        def_register_universe_snapshot(
            con=con,
            universe=universe,
            universe_source=universe_source,
        )

        def_upsert_holdings(
            con=con,
            latest=latest,
        )

        def_insert_fetch_status(
            con=con,
            status=status_df,
        )

        change_count = (
            def_rebuild_latest_changes(
                con
            )
        )

        parquet_partition_count = (
            def_export_holdings_parquet(
                con=con,
                parquet_root=parquet_root,
            )
        )

        def_export_reference_parquets(
            con=con,
            parquet_root=parquet_root,
        )

        total_rows = int(
            con.execute(
                "SELECT COUNT(*) FROM holdings_daily"
            ).fetchone()[0]
        )

        distinct_etf = int(
            con.execute(
                "SELECT COUNT(DISTINCT etf_ticker) FROM holdings_daily"
            ).fetchone()[0]
        )

        distinct_dates = int(
            con.execute(
                "SELECT COUNT(DISTINCT portfolio_date) FROM holdings_daily"
            ).fetchone()[0]
        )

    finally:
        con.close()

    status_df.to_csv(
        output_dir
        / "ActiveTWETF_Fetch_Status_Latest.csv",
        index=False,
        encoding=CSV_ENCODING,
    )

    manifest = {
        "engine": ENGINE_NAME,
        "version": ENGINE_VERSION,
        "run_at": datetime.now()
        .astimezone()
        .isoformat(
            timespec="seconds"
        ),
        "universe_source": universe_source,
        "universe_count": len(
            universe
        ),
        "selected_count": len(
            selected
        ),
        "fetch_pass_count": int(
            status_df[
                "status"
            ].eq(
                "PASS"
            ).sum()
        ),
        "fetch_fail_count": int(
            status_df[
                "status"
            ].eq(
                "FAIL"
            ).sum()
        ),
        "latest_rows": len(
            latest
        ),
        "duckdb_total_rows": total_rows,
        "duckdb_distinct_etf": distinct_etf,
        "duckdb_distinct_dates": distinct_dates,
        "change_count": change_count,
        "parquet_partition_count": parquet_partition_count,
        "duckdb_path": str(
            duckdb_path
        ),
        "parquet_root": str(
            parquet_root
        ),
    }

    manifest[
        "status"
    ] = (
        "FAIL"
        if manifest[
            "fetch_pass_count"
        ] == 0
        else "PARTIAL"
        if manifest[
            "fetch_fail_count"
        ] > 0
        else "PASS"
    )

    (
        output_dir
        / "manifest_latest.json"
    ).write_text(
        json.dumps(
            manifest,
            ensure_ascii=False,
            indent=2,
        ),
        encoding="utf-8",
    )

    return manifest


