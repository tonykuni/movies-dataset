def def_clean_text(value: Any) -> str:
    if value is None:
        return ""

    return re.sub(
        r"\s+",
        " ",
        str(value).replace(
            "\xa0",
            " ",
        ),
    ).strip()


def def_parse_float(
    value: Any,
) -> Optional[float]:
    text = def_clean_text(
        value
    )

    if not text:
        return None

    text = (
        text.replace(
            ",",
            "",
        )
        .replace(
            "%",
            "",
        )
        .strip()
    )

    match = re.search(
        r"-?\d+(?:\.\d+)?",
        text,
    )

    if not match:
        return None

    try:
        return float(
            match.group(0)
        )
    except ValueError:
        return None


def def_extract_stock_identity(
    value: str,
) -> Tuple[str, str, str]:
    text = def_clean_text(
        value
    )

    match = re.search(
        r"([0-9]{4}[A-Z]?)\.(TW|TWO)",
        text,
        flags=re.IGNORECASE,
    )

    if match:
        raw = match.group(
            1
        ).upper()

        suffix = match.group(
            2
        ).upper()

        name = re.sub(
            r"\(?[0-9]{4}[A-Z]?\.(?:TW|TWO)\)?",
            "",
            text,
            flags=re.IGNORECASE,
        ).strip()

        return (
            raw,
            f"{raw}.{suffix}",
            name,
        )

    match = re.search(
        r"\b([0-9]{4}[A-Z]?)\b",
        text,
    )

    if match:
        raw = match.group(
            1
        ).upper()

        name = re.sub(
            rf"\b{re.escape(raw)}\b",
            "",
            text,
        ).strip(
            " -()"
        )

        return (
            raw,
            f"{raw}.TW",
            name,
        )

    return (
        "",
        "",
        text,
    )


def def_extract_portfolio_date(
    html: str,
) -> str:
    text = BeautifulSoup(
        html,
        "html.parser",
    ).get_text(
        " ",
        strip=True,
    )

    patterns = (
        r"資料日期[:：]?\s*(20\d{2})[/-](\d{1,2})[/-](\d{1,2})",
        r"(20\d{2})[/-](\d{1,2})[/-](\d{1,2})",
    )

    for pattern in patterns:
        match = re.search(
            pattern,
            text,
        )

        if match:
            year, month, day = (
                match.groups()
            )

            return (
                f"{int(year):04d}/"
                f"{int(month):02d}/"
                f"{int(day):02d}"
            )

    return ""


