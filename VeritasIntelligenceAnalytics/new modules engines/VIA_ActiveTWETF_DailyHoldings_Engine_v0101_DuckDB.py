def def_main() -> int:
    args = def_parse_args()

    def_setup_logging(
        args.verbose
    )

    if args.self_test:
        result = def_self_test(
            Path(
                args.output_dir
            )
            / "_self_test"
        )

        print(
            json.dumps(
                result,
                ensure_ascii=False,
                indent=2,
            )
        )

        return (
            0
            if result[
                "all_pass"
            ]
            else 3
        )

    try:
        manifest = (
            def_fetch_daily_holdings(
                output_dir=Path(
                    args.output_dir
                ),
                universe_csv=Path(
                    args.universe_csv
                ),
                duckdb_path=Path(
                    args.duckdb_path
                ),
                parquet_root=Path(
                    args.parquet_root
                ),
                tickers=args.tickers,
            )
        )

        print(
            json.dumps(
                manifest,
                ensure_ascii=False,
                indent=2,
            )
        )

        return (
            0
            if manifest[
                "status"
            ]
            in (
                "PASS",
                "PARTIAL",
            )
            else 2
        )

    except Exception as exc:
        logging.exception(
            "FAIL_CLOSED: %s",
            exc,
        )

        return 2


