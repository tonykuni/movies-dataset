def def_register_universe_snapshot(
    con: Any,
    universe: Dict[str, Dict[str, str]],
    universe_source: str,
) -> None:
    rows = [
        {
            "snapshot_at": datetime.now(),
            "etf_ticker": ticker,
            "etf_name": meta[
                "name"
            ],
            "issuer": meta[
                "issuer"
            ],
            "universe_source": universe_source,
        }
        for ticker, meta in sorted(
            universe.items()
        )
    ]

    df = pd.DataFrame(
        rows
    )

    con.register(
        "universe_stage",
        df,
    )

    con.execute(
        """
        INSERT INTO active_tw_etf_universe
        SELECT
            snapshot_at,
            etf_ticker,
            etf_name,
            issuer,
            universe_source
        FROM universe_stage
        """
    )

    con.unregister(
        "universe_stage"
    )


def def_upsert_holdings(
    con: Any,
    latest: pd.DataFrame,
) -> None:
    if latest.empty:
        return

    stage = latest.copy()

    stage[
        "portfolio_date"
    ] = pd.to_datetime(
        stage[
            "portfolio_date"
        ],
        errors="coerce",
    ).dt.date

    stage[
        "fetched_at"
    ] = pd.to_datetime(
        stage[
            "fetched_at"
        ],
        errors="coerce",
    )

    con.register(
        "holdings_stage",
        stage,
    )

    # DuckDB portable idempotent pattern:
    # delete same natural keys, then insert current snapshot.
    con.execute(
        """
        DELETE FROM holdings_daily
        USING holdings_stage s
        WHERE holdings_daily.portfolio_date = s.portfolio_date
          AND holdings_daily.etf_ticker = s.etf_ticker
          AND holdings_daily.holding_ticker = s.holding_ticker
        """
    )

    con.execute(
        """
        INSERT INTO holdings_daily
        SELECT
            portfolio_date,
            etf_ticker,
            etf_yf_ticker,
            etf_name,
            issuer,
            holding_ticker,
            holding_yf_ticker,
            holding_name,
            weight_pct,
            shares,
            source_type,
            source_url,
            fetched_at
        FROM holdings_stage
        """
    )

    con.unregister(
        "holdings_stage"
    )


def def_insert_fetch_status(
    con: Any,
    status: pd.DataFrame,
) -> None:
    if status.empty:
        return

    stage = status.copy()

    stage.insert(
        0,
        "run_at",
        datetime.now(),
    )

    stage[
        "portfolio_date"
    ] = pd.to_datetime(
        stage[
            "portfolio_date"
        ],
        errors="coerce",
    ).dt.date

    con.register(
        "status_stage",
        stage,
    )

    con.execute(
        """
        INSERT INTO fetch_status
        SELECT
            run_at,
            etf_ticker,
            status,
            source_type,
            holding_count,
            portfolio_date,
            errors
        FROM status_stage
        """
    )

    con.unregister(
        "status_stage"
    )


