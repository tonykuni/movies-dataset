def def_find_holdings_table(
    html: str,
) -> pd.DataFrame:
    tables = pd.read_html(
        io.StringIO(
            html
        )
    )

    best: Optional[
        pd.DataFrame
    ] = None

    best_score = -1

    for table in tables:
        df = table.copy()

        if isinstance(
            df.columns,
            pd.MultiIndex,
        ):
            df.columns = [
                " ".join(
                    def_clean_text(
                        x
                    )
                    for x in col
                    if def_clean_text(
                        x
                    )
                )
                for col in df.columns
            ]
        else:
            df.columns = [
                def_clean_text(
                    x
                )
                for x in df.columns
            ]

        columns_text = " ".join(
            df.columns
        )

        score = 0

        for keyword, weight in (
            ("個股名稱", 4),
            ("投資比例", 4),
            ("持有股數", 4),
            ("持股權重", 3),
            ("股票代號", 2),
            ("股票名稱", 2),
        ):
            if keyword in columns_text:
                score += weight

        if score > best_score:
            best = df
            best_score = score

    if (
        best is None
        or best_score < 6
    ):
        raise RuntimeError(
            "HOLDINGS_TABLE_NOT_FOUND"
        )

    return best


