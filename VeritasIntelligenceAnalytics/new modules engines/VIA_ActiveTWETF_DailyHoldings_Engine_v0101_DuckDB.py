def def_require_duckdb() -> None:
    if duckdb is None:
        raise RuntimeError(
            "DUCKDB_NOT_INSTALLED: install with "
            "`python -m pip install duckdb` in the VIA runtime environment."
        )


def def_open_duckdb(
    db_path: Path,
):
    def_require_duckdb()

    db_path = Path(
        db_path
    )

    db_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    con = duckdb.connect(
        str(
            db_path
        )
    )

    con.execute(
        """
        CREATE TABLE IF NOT EXISTS active_tw_etf_universe (
            snapshot_at TIMESTAMP,
            etf_ticker VARCHAR,
            etf_name VARCHAR,
            issuer VARCHAR,
            universe_source VARCHAR
        )
        """
    )

    con.execute(
        """
        CREATE TABLE IF NOT EXISTS holdings_daily (
            portfolio_date DATE,
            etf_ticker VARCHAR,
            etf_yf_ticker VARCHAR,
            etf_name VARCHAR,
            issuer VARCHAR,
            holding_ticker VARCHAR,
            holding_yf_ticker VARCHAR,
            holding_name VARCHAR,
            weight_pct DOUBLE,
            shares DOUBLE,
            source_type VARCHAR,
            source_url VARCHAR,
            fetched_at TIMESTAMP
        )
        """
    )

    con.execute(
        """
        CREATE TABLE IF NOT EXISTS fetch_status (
            run_at TIMESTAMP,
            etf_ticker VARCHAR,
            status VARCHAR,
            source_type VARCHAR,
            holding_count BIGINT,
            portfolio_date DATE,
            errors VARCHAR
        )
        """
    )

    con.execute(
        """
        CREATE TABLE IF NOT EXISTS holdings_changes (
            portfolio_date DATE,
            previous_date DATE,
            etf_ticker VARCHAR,
            holding_ticker VARCHAR,
            holding_name VARCHAR,
            change_type VARCHAR,
            shares_previous DOUBLE,
            shares_current DOUBLE,
            shares_change DOUBLE,
            weight_previous DOUBLE,
            weight_current DOUBLE,
            weight_change DOUBLE
        )
        """
    )

    return con


