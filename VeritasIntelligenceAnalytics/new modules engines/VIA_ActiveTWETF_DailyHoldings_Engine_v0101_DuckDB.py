def def_quality_gate_holdings(
    df: pd.DataFrame,
    etf_ticker: str,
) -> List[str]:
    errors: List[
        str
    ] = []

    if df.empty:
        return [
            "HOLDINGS_EMPTY"
        ]

    if (
        df[
            "etf_ticker"
        ].nunique()
        != 1
    ):
        errors.append(
            "MULTIPLE_ETF_TICKERS"
        )

    if (
        str(
            df[
                "etf_ticker"
            ].iloc[0]
        )
        != etf_ticker
    ):
        errors.append(
            "ETF_TICKER_MISMATCH"
        )

    if (
        df[
            "holding_ticker"
        ].duplicated().any()
    ):
        errors.append(
            "DUPLICATE_HOLDING_TICKER"
        )

    if (
        df[
            "portfolio_date"
        ].eq(
            ""
        ).all()
    ):
        errors.append(
            "PORTFOLIO_DATE_MISSING"
        )

    total_weight = float(
        df[
            "weight_pct"
        ].sum()
    )

    if total_weight <= 10:
        errors.append(
            f"TOTAL_STOCK_WEIGHT_TOO_LOW:{total_weight:.2f}"
        )

    if total_weight > 110:
        errors.append(
            f"TOTAL_STOCK_WEIGHT_TOO_HIGH:{total_weight:.2f}"
        )

    if len(df) < 3:
        errors.append(
            f"TOO_FEW_HOLDINGS:{len(df)}"
        )

    return errors


