def def_rebuild_latest_changes(
    con: Any,
) -> int:
    con.execute(
        "DELETE FROM holdings_changes"
    )

    con.execute(
        """
        INSERT INTO holdings_changes
        WITH dates AS (
            SELECT
                etf_ticker,
                portfolio_date,
                DENSE_RANK() OVER (
                    PARTITION BY etf_ticker
                    ORDER BY portfolio_date DESC
                ) AS date_rank
            FROM (
                SELECT DISTINCT
                    etf_ticker,
                    portfolio_date
                FROM holdings_daily
            )
        ),
        latest AS (
            SELECT h.*
            FROM holdings_daily h
            JOIN dates d
              ON h.etf_ticker = d.etf_ticker
             AND h.portfolio_date = d.portfolio_date
            WHERE d.date_rank = 1
        ),
        previous AS (
            SELECT h.*
            FROM holdings_daily h
            JOIN dates d
              ON h.etf_ticker = d.etf_ticker
             AND h.portfolio_date = d.portfolio_date
            WHERE d.date_rank = 2
        ),
        joined AS (
            SELECT
                COALESCE(l.portfolio_date, p.portfolio_date) AS portfolio_date,
                p.portfolio_date AS previous_date,
                COALESCE(l.etf_ticker, p.etf_ticker) AS etf_ticker,
                COALESCE(l.holding_ticker, p.holding_ticker) AS holding_ticker,
                COALESCE(l.holding_name, p.holding_name) AS holding_name,
                p.shares AS shares_previous,
                l.shares AS shares_current,
                p.weight_pct AS weight_previous,
                l.weight_pct AS weight_current
            FROM latest l
            FULL OUTER JOIN previous p
              ON l.etf_ticker = p.etf_ticker
             AND l.holding_ticker = p.holding_ticker
        )
        SELECT
            portfolio_date,
            previous_date,
            etf_ticker,
            holding_ticker,
            holding_name,
            CASE
                WHEN shares_previous IS NULL THEN 'ADDED'
                WHEN shares_current IS NULL THEN 'REMOVED'
                WHEN COALESCE(shares_current, 0) > COALESCE(shares_previous, 0)
                    THEN 'INCREASED'
                WHEN COALESCE(shares_current, 0) < COALESCE(shares_previous, 0)
                    THEN 'DECREASED'
                ELSE 'WEIGHT_CHANGED'
            END AS change_type,
            shares_previous,
            shares_current,
            COALESCE(shares_current, 0) - COALESCE(shares_previous, 0)
                AS shares_change,
            weight_previous,
            weight_current,
            COALESCE(weight_current, 0) - COALESCE(weight_previous, 0)
                AS weight_change
        FROM joined
        WHERE
            shares_previous IS NULL
            OR shares_current IS NULL
            OR COALESCE(shares_current, 0) <> COALESCE(shares_previous, 0)
            OR ABS(
                COALESCE(weight_current, 0)
                - COALESCE(weight_previous, 0)
            ) > 0.0000001
        """
    )

    return int(
        con.execute(
            "SELECT COUNT(*) FROM holdings_changes"
        ).fetchone()[0]
    )


