def def_fetch_one_etf(
    session: requests.Session,
    etf_ticker: str,
    meta: Dict[str, str],
) -> Tuple[
    pd.DataFrame,
    Dict[str, Any],
]:
    errors: List[
        str
    ] = []

    try:
        official = (
            def_fetch_from_issuer(
                session,
                etf_ticker,
                meta,
            )
        )

        gate = (
            def_quality_gate_holdings(
                official,
                etf_ticker,
            )
        )

        if not gate:
            return (
                official,
                {
                    "etf_ticker": etf_ticker,
                    "status": "PASS",
                    "source_type": "ISSUER_OFFICIAL",
                    "holding_count": len(
                        official
                    ),
                    "portfolio_date": str(
                        official[
                            "portfolio_date"
                        ].iloc[0]
                    ),
                    "errors": "",
                },
            )

        errors.extend(
            [
                "ISSUER:"
                + item
                for item in gate
            ]
        )

    except Exception as exc:
        errors.append(
            "ISSUER:"
            + type(
                exc
            ).__name__
            + ":"
            + str(
                exc
            )
        )

    try:
        fallback = (
            def_fetch_from_moneydj(
                session,
                etf_ticker,
                meta,
            )
        )

        gate = (
            def_quality_gate_holdings(
                fallback,
                etf_ticker,
            )
        )

        if not gate:
            return (
                fallback,
                {
                    "etf_ticker": etf_ticker,
                    "status": "PASS",
                    "source_type": "MONEYDJ_FALLBACK",
                    "holding_count": len(
                        fallback
                    ),
                    "portfolio_date": str(
                        fallback[
                            "portfolio_date"
                        ].iloc[0]
                    ),
                    "errors": " | ".join(
                        errors
                    ),
                },
            )

        errors.extend(
            [
                "MONEYDJ:"
                + item
                for item in gate
            ]
        )

    except Exception as exc:
        errors.append(
            "MONEYDJ:"
            + type(
                exc
            ).__name__
            + ":"
            + str(
                exc
            )
        )

    return (
        pd.DataFrame(
            columns=HOLDING_COLUMNS
        ),
        {
            "etf_ticker": etf_ticker,
            "status": "FAIL",
            "source_type": "",
            "holding_count": 0,
            "portfolio_date": "",
            "errors": " | ".join(
                errors
            ),
        },
    )


