def def_normalize_holdings(
    df: pd.DataFrame,
) -> pd.DataFrame:
    if df.empty:
        return pd.DataFrame(
            columns=HOLDING_COLUMNS
        )

    out = df.copy()

    for col in (
        "etf_ticker",
        "holding_ticker",
    ):
        out[col] = (
            out[col]
            .astype(str)
            .str.strip()
            .str.upper()
        )

    out[
        "weight_pct"
    ] = pd.to_numeric(
        out[
            "weight_pct"
        ],
        errors="coerce",
    )

    out[
        "shares"
    ] = pd.to_numeric(
        out[
            "shares"
        ],
        errors="coerce",
    )

    out = out.dropna(
        subset=[
            "weight_pct",
        ]
    )

    out = out.loc[
        out[
            "weight_pct"
        ].between(
            0,
            100,
            inclusive="both",
        )
    ].copy()

    out = out.drop_duplicates(
        subset=[
            "portfolio_date",
            "etf_ticker",
            "holding_ticker",
        ],
        keep="last",
    )

    return out[
        HOLDING_COLUMNS
    ].reset_index(
        drop=True
    )


def def_parse_moneydj_holdings(
    html: str,
    etf_ticker: str,
    etf_name: str,
    issuer: str,
    source_url: str,
) -> pd.DataFrame:
    table = def_find_holdings_table(
        html
    )

    name_col = next(
        (
            c
            for c in table.columns
            if (
                "個股名稱" in c
                or "股票名稱與代號" in c
                or "股票名稱" in c
            )
        ),
        None,
    )

    code_col = next(
        (
            c
            for c in table.columns
            if "股票代號" in c
        ),
        None,
    )

    weight_col = next(
        (
            c
            for c in table.columns
            if (
                "投資比例" in c
                or "持股權重" in c
                or "權重" in c
            )
        ),
        None,
    )

    shares_col = next(
        (
            c
            for c in table.columns
            if "股數" in c
        ),
        None,
    )

    if (
        name_col is None
        or weight_col is None
    ):
        raise RuntimeError(
            "MONEYDJ_REQUIRED_COLUMNS_MISSING"
        )

    portfolio_date = (
        def_extract_portfolio_date(
            html
        )
    )

    fetched_at = (
        datetime.now()
        .astimezone()
        .isoformat(
            timespec="seconds"
        )
    )

    rows: List[
        Dict[str, Any]
    ] = []

    for row in table.to_dict(
        "records"
    ):
        raw_value = def_clean_text(
            row.get(
                name_col,
                "",
            )
        )

        if code_col:
            raw_value = (
                def_clean_text(
                    row.get(
                        code_col,
                        "",
                    )
                )
                + " "
                + raw_value
            ).strip()

        (
            holding_ticker,
            holding_yf_ticker,
            holding_name,
        ) = def_extract_stock_identity(
            raw_value
        )

        weight = def_parse_float(
            row.get(
                weight_col
            )
        )

        shares = (
            def_parse_float(
                row.get(
                    shares_col
                )
            )
            if shares_col
            else None
        )

        if (
            not holding_ticker
            or weight is None
        ):
            continue

        rows.append(
            {
                "portfolio_date": portfolio_date,
                "etf_ticker": etf_ticker,
                "etf_yf_ticker": f"{etf_ticker}.TW",
                "etf_name": etf_name,
                "issuer": issuer,
                "holding_ticker": holding_ticker,
                "holding_yf_ticker": holding_yf_ticker,
                "holding_name": holding_name,
                "weight_pct": weight,
                "shares": shares,
                "source_type": "MONEYDJ_FALLBACK",
                "source_url": source_url,
                "fetched_at": fetched_at,
            }
        )

    return def_normalize_holdings(
        pd.DataFrame(
            rows,
            columns=HOLDING_COLUMNS,
        )
    )


