def machine_factor() -> tuple:
    """量這台機器比基準慢幾倍。固定工作量,取三次中位數。
    夾在 [1.0, 8.0]:**永不縮短**宣告的逾時(只增不減),也不讓離群值把上限炸掉。
    `VIA_GRID_TIME_FACTOR` 可由操作員直接指定(他的手優先於我的量測)。"""
    if _CALIB["factor"] is not None:
        return _CALIB["factor"], _CALIB["why"]
    env = os.environ.get("VIA_GRID_TIME_FACTOR", "").strip()
    if env:
        try:
            f = max(1.0, min(8.0, float(env)))
            _CALIB.update(factor=f, why=f"操作員指定 VIA_GRID_TIME_FACTOR={env}")
            return f, _CALIB["why"]
        except Exception:
            pass
    xs = []
    for _ in range(3):
        t0 = time.perf_counter()
        acc = 0
        for i in range(300000):
            acc += i * i % 7
        try:
            subprocess.run([sys.executable, "-c", "pass"], capture_output=True, timeout=60)
        except Exception:
            pass
        xs.append(time.perf_counter() - t0)
    med = sorted(xs)[1]
    f = max(1.0, min(8.0, med / CALIB_BASELINE_SEC))
    _CALIB.update(factor=round(f, 2),
                  why=f"校準 {med:.3f}s / 容器基準 {CALIB_BASELINE_SEC:.3f}s → ×{f:.2f}")
    return _CALIB["factor"], _CALIB["why"]


def scaled_timeout(sec: int) -> int:
    f, _ = machine_factor()
    return int(round(sec * f))


