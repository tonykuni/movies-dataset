    try {
        $null = [IO.Directory]::CreateDirectory($TemporaryRoot)

        def-WriteStep -Percent 4 -Message "Expand embedded engines and verify SHA-256"
        def-ExpandVerifiedPayload -Base64 $MotherRootPayloadBase64 -ExpectedSha256 $MotherRootPayloadSha256 -DestinationPath $MotherRootScriptPath
        def-ExpandVerifiedPayload -Base64 $FormulaPayloadBase64 -ExpectedSha256 $FormulaPayloadSha256 -DestinationPath $FormulaScriptPath

        def-WriteStep -Percent 6 -Message "Native PowerShell AST validation for both embedded engines"
        def-TestPowerShellAst -Path $MotherRootScriptPath
        def-TestPowerShellAst -Path $FormulaScriptPath

        def-WriteStep -Percent 8 -Message "Stage 1/2 · reconcile, safely promote and activate canonical VIA mother root"
        $MotherOutput = @(& $MotherRootScriptPath)
        $MotherEvidence = def-GetGateEvidence -Output $MotherOutput -Stage "Mother-root reconciliation"

        if ([string]$MotherEvidence.gate -notmatch '^CANONICAL_MOTHER_ROOT_ACTIVE(?:_WITH_REVIEW_HOLDS)?$') {
            throw "Mother-root authority gate failed: $($MotherEvidence.gate)"
        }

        if ([string]::IsNullOrWhiteSpace($env:VIA_MOTHER_ROOT)) {
            $env:VIA_MOTHER_ROOT = $ResolvedCanonicalRoot
        }

        def-AssertNoOneDrivePath -Path $env:VIA_MOTHER_ROOT -Role "activated VIA_MOTHER_ROOT"

        def-WriteStep -Percent 74 -Message "Stage 2/2 · install and validate dynamic normalized_close formula"
        $FormulaOutput = @(& $FormulaScriptPath)
        $FormulaEvidence = def-GetGateEvidence -Output $FormulaOutput -Stage "Dynamic formula integration"

        if ([string]$FormulaEvidence.gate -notmatch '^DYNAMIC_FORMULA_INTEGRATION_PASS(?:_SMOKE_PENDING)?$') {
            throw "Dynamic formula integration gate failed: $($FormulaEvidence.gate)"
        }
    }
    finally {
        if (Test-Path -LiteralPath $TemporaryRoot) {
            Remove-Item -LiteralPath $TemporaryRoot -Recurse -Force
        }
    }

    $HasReview = (
        [string]$MotherEvidence.gate -match 'REVIEW_HOLDS' -or
        [string]$FormulaEvidence.gate -match 'SMOKE_PENDING'
    )
    $FinalGate = if ($HasReview) {
        "VIA_ALL_IN_ONE_PASS_WITH_REVIEW"
    }
    else {
        "VIA_ALL_IN_ONE_PASS"
    }

    def-WriteStep -Percent 100 -Message "OneClick governance, mother root and dynamic formula complete" -Status $(if ($HasReview) { "WARN" } else { "PASS" })

    Write-Host ""
    Write-Host "def Final Gate          : $FinalGate" -ForegroundColor $(if ($HasReview) { "Yellow" } else { "Green" })
    Write-Host "def Mother Gate         : $($MotherEvidence.gate)"
    Write-Host "def Initial Pointer     : $($MotherEvidence.initial_mother_root_pointer_state.Overall)"
    Write-Host "def Checkpoint Gate     : $($MotherEvidence.pre_promotion_checkpoint.Gate)"
    Write-Host "def Checkpoint Barrier  : $($MotherEvidence.pre_promotion_checkpoint.BarrierPath)"
    Write-Host "def Formula Gate        : $($FormulaEvidence.gate)"
    Write-Host "def Git Worktree        : $ResolvedGitWorktree" -ForegroundColor Green
    Write-Host "def VIA Mother Root     : $env:VIA_MOTHER_ROOT" -ForegroundColor Green
    Write-Host "def VIA_PYTHON          : $env:VIA_PYTHON" -ForegroundColor $(if ([string]::IsNullOrWhiteSpace($env:VIA_PYTHON)) { "Yellow" } else { "Green" })
    Write-Host "def Environments        : via_core* / via_* / .venv"
    Write-Host "def Hash Workers        : $HashThrottleLimit"
    Write-Host "def Hash Batch Size     : $HashBatchSize"
    Write-Host "def Hash Heartbeat      : every $HashHeartbeatSeconds seconds"
    Write-Host "def Hash Timeout        : $HashBatchTimeoutSeconds seconds minimum + size allowance"
    Write-Host "def Round 3 Full Rehash : $Round3FullCanonicalRehash"
    Write-Host "def Formula             : normalized_base * effective_close(t) / effective_close(base_date)"
    Write-Host "def Database Created    : 0" -ForegroundColor Green
    Write-Host "def Persisted Rows      : 0" -ForegroundColor Green
    Write-Host "def OneDrive            : PROHIBITED / ACCESSED=0" -ForegroundColor Green
    Write-Host "def Legacy Deleted      : 0" -ForegroundColor Green
    Write-Host "def Git Commit / Push   : 0 / 0" -ForegroundColor Green
    Write-Host "def Hydra               : 0" -ForegroundColor Green
    Write-Host "def PowerShell          : remains open" -ForegroundColor Green

    if (-not $KeepPowerShellOpen) {
        Write-Warning "KeepPowerShellOpen is false, but this script never calls exit."
    }

    return [pscustomobject]@{
        gate = $FinalGate
        mother_gate = $MotherEvidence.gate
        initial_mother_root_pointer_state = $MotherEvidence.initial_mother_root_pointer_state
        pre_promotion_checkpoint = $MotherEvidence.pre_promotion_checkpoint
        formula_gate = $FormulaEvidence.gate
        git_worktree = $ResolvedGitWorktree
        via_mother_root = $env:VIA_MOTHER_ROOT
        via_python = $env:VIA_PYTHON
        formula = $FormulaEvidence.formula
        database_created = $false
        normalized_rows_persisted = 0
        onedrive_policy = "PROHIBITED"
        onedrive_accessed = 0
        legacy_deleted = $false
        git_commit_created = $false
        git_push_performed = $false
        hydra = 0
        started_utc = $StartedUtc.ToString("o")
        completed_utc = [DateTime]::UtcNow.ToString("o")
    }
}


