function def-WriteStep {
    param(
        [Parameter(Mandatory)]
        [ValidateRange(0, 100)]
        [int]$Percent,

        [Parameter(Mandatory)]
        [string]$Message,

        [ValidateSet("INFO", "PASS", "WARN", "FAIL")]
        [string]$Status = "INFO"
    )

    $Width = 24
    $Filled = [Math]::Floor($Width * $Percent / 100)
    $Empty = $Width - $Filled
    $Bar = ("█" * $Filled) + ("░" * $Empty)
    $Color = switch ($Status) {
        "PASS" { "Green" }
        "WARN" { "Yellow" }
        "FAIL" { "Red" }
        default { "Cyan" }
    }

    Write-Host (
        "def [{0,3}%] [{1}] [{2}] {3}" -f
        $Percent,
        $Bar,
        $Status,
        $Message
    ) -ForegroundColor $Color
}

function def-TestPathIsOneDrive {
    param(
        [Parameter(Mandatory)]
        [string]$Path
    )

    if ([string]::IsNullOrWhiteSpace($Path)) {
        return $false
    }

    $FullPath = try {
        [IO.Path]::GetFullPath(
            [Environment]::ExpandEnvironmentVariables($Path)
        )
    }
    catch {
        $Path
    }

    if ($FullPath -match '(?i)(?:^|[\\/])OneDrive(?:\s*-\s*[^\\/]+)?(?:[\\/]|$)') {
        return $true
    }

    foreach ($KnownOneDriveRoot in @(
        $env:OneDrive,
        $env:OneDriveCommercial,
        $env:OneDriveConsumer
    )) {
        if ([string]::IsNullOrWhiteSpace($KnownOneDriveRoot)) {
            continue
        }

        $ResolvedKnownRoot = try {
            [IO.Path]::GetFullPath($KnownOneDriveRoot).TrimEnd(
                [IO.Path]::DirectorySeparatorChar,
                [IO.Path]::AltDirectorySeparatorChar
            )
        }
        catch {
            continue
        }

        if (
            $FullPath.Equals(
                $ResolvedKnownRoot,
                [StringComparison]::OrdinalIgnoreCase
            ) -or
            $FullPath.StartsWith(
                $ResolvedKnownRoot + [IO.Path]::DirectorySeparatorChar,
                [StringComparison]::OrdinalIgnoreCase
            )
        ) {
            return $true
        }
    }

    return $false
}

function def-AssertNoOneDrivePath {
    param(
        [Parameter(Mandatory)]
        [string]$Path,

        [Parameter(Mandatory)]
        [string]$Role
    )

    if (def-TestPathIsOneDrive -Path $Path) {
        throw ("OneDrive is prohibited for {0}: {1}" -f $Role, $Path)
    }
}

function def-AssertCanonicalWithinGitWorktree {
    param(
        [Parameter(Mandatory)]
        [string]$CanonicalRoot,

        [Parameter(Mandatory)]
        [string]$GitRoot
    )

    $ResolvedCanonical = [IO.Path]::GetFullPath($CanonicalRoot).TrimEnd(
        [IO.Path]::DirectorySeparatorChar,
        [IO.Path]::AltDirectorySeparatorChar
    )
    $ResolvedGit = [IO.Path]::GetFullPath($GitRoot).TrimEnd(
        [IO.Path]::DirectorySeparatorChar,
        [IO.Path]::AltDirectorySeparatorChar
    )
    $Prefix = $ResolvedGit + [IO.Path]::DirectorySeparatorChar

    if (
        -not $ResolvedCanonical.StartsWith(
            $Prefix,
            [StringComparison]::OrdinalIgnoreCase
        )
    ) {
        throw (
            "Canonical VIA mother root must be a governed subdirectory of " +
            "the Git worktree. Git=$ResolvedGit Canonical=$ResolvedCanonical"
        )
    }
}

function def-GetSha256 {
    param(
        [Parameter(Mandatory)]
        [string]$Path
    )

    return (Get-FileHash -LiteralPath $Path -Algorithm SHA256).Hash.ToUpperInvariant()
}


