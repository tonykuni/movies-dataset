function def-ExpandVerifiedPayload {
    param(
        [Parameter(Mandatory)]
        [string]$Base64,

        [Parameter(Mandatory)]
        [string]$ExpectedSha256,

        [Parameter(Mandatory)]
        [string]$DestinationPath
    )

    $CompressedBytes = [Convert]::FromBase64String($Base64)
    $MemoryStream = [IO.MemoryStream]::new($CompressedBytes, $false)
    $GzipStream = [IO.Compression.GZipStream]::new(
        $MemoryStream,
        [IO.Compression.CompressionMode]::Decompress
    )
    $OutputStream = [IO.File]::Create($DestinationPath)

    try {
        $GzipStream.CopyTo($OutputStream)
    }
    finally {
        $OutputStream.Dispose()
        $GzipStream.Dispose()
        $MemoryStream.Dispose()
    }

    $ActualSha256 = def-GetSha256 -Path $DestinationPath
    if ($ActualSha256 -ne $ExpectedSha256.ToUpperInvariant()) {
        throw (
            "Embedded payload integrity failure. Expected=$ExpectedSha256 " +
            "Actual=$ActualSha256 File=$DestinationPath"
        )
    }
}

function def-TestPowerShellAst {
    param(
        [Parameter(Mandatory)]
        [string]$Path
    )

    $Tokens = $null
    $ParseErrors = $null
    $null = [Management.Automation.Language.Parser]::ParseFile(
        $Path,
        [ref]$Tokens,
        [ref]$ParseErrors
    )

    if (@($ParseErrors).Count -gt 0) {
        $Messages = @($ParseErrors | ForEach-Object Message) -join " | "
        throw ("PowerShell AST validation failed for {0}: {1}" -f $Path, $Messages)
    }
}

function def-GetGateEvidence {
    param(
        [Parameter(Mandatory)]
        [object[]]$Output,

        [Parameter(Mandatory)]
        [string]$Stage
    )

    $Evidence = $null
    foreach ($Item in @($Output)) {
        if (
            $null -ne $Item -and
            $null -ne $Item.PSObject.Properties["gate"]
        ) {
            $Evidence = $Item
        }
    }

    if ($null -eq $Evidence) {
        throw "$Stage did not return governed gate evidence."
    }

    return $Evidence
}


