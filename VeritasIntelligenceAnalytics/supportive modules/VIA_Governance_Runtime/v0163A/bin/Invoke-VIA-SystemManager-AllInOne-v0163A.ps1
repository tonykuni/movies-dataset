function Expand-GzipBase64 {
    param(
        [Parameter(Mandatory)][string]$Payload
    )

    $compact = $Payload -replace "\s", ""
    $compressed = [Convert]::FromBase64String($compact)
    $input = [System.IO.MemoryStream]::new($compressed)
    $gzip = [System.IO.Compression.GZipStream]::new(
        $input,
        [System.IO.Compression.CompressionMode]::Decompress
    )
    $output = [System.IO.MemoryStream]::new()

    try {
        $gzip.CopyTo($output)
        return $output.ToArray()
    }
    finally {
        $gzip.Dispose()
        $input.Dispose()
        $output.Dispose()
    }
}

function Install-EmbeddedAsset {
    param(
        [Parameter(Mandatory)]$Asset,
        [Parameter(Mandatory)][string]$RuntimeRoot
    )

    $destination = Join-Path `
        -Path $RuntimeRoot `
        -ChildPath ([string]$Asset.RelativePath)

    Ensure-Directory -Path (Split-Path -Parent $destination)

    if (Test-Path -LiteralPath $destination -PathType Leaf) {
        $existingSha = Get-Sha256 -Path $destination

        if ($existingSha -ne [string]$Asset.ExpectedSHA) {
            throw (
                "Embedded runtime destination has an unexpected SHA256: " +
                "$destination Expected=$($Asset.ExpectedSHA) Actual=$existingSha"
            )
        }

        return [ordered]@{
            component = [string]$Asset.Key
            state = "EXACT_EXISTS_SKIP"
            path = $destination
            sha256 = $existingSha
        }
    }

    $bytes = Expand-GzipBase64 -Payload ([string]$Asset.Payload)
    $actual = (
        [BitConverter]::ToString(
            [System.Security.Cryptography.SHA256]::HashData($bytes)
        )
    ).Replace("-", "").ToLowerInvariant()

    if ($actual -ne [string]$Asset.ExpectedSHA) {
        throw (
            "Embedded payload SHA256 mismatch: " +
            "$($Asset.Key) Expected=$($Asset.ExpectedSHA) Actual=$actual"
        )
    }

    $temporary = "{0}.tmp.{1}.{2}" -f
        $destination,
        $PID,
        ([DateTime]::UtcNow.Ticks)

    [System.IO.File]::WriteAllBytes($temporary, $bytes)
    [System.IO.File]::Move($temporary, $destination, $false)

    if ((Get-Sha256 -Path $destination) -ne [string]$Asset.ExpectedSHA) {
        throw "Post-write SHA256 verification failed: $destination"
    }

    return [ordered]@{
        component = [string]$Asset.Key
        state = "DEPLOYED_EXACT"
        path = $destination
        sha256 = $actual
    }
}

function Install-Self {
    param(
        [Parameter(Mandatory)][string]$RuntimeRoot
    )

    $destination = Join-Path `
        -Path $RuntimeRoot `
        -ChildPath ("bin\" + $Script:MasterName)

    Ensure-Directory -Path (Split-Path -Parent $destination)

    $source = [System.IO.Path]::GetFullPath($PSCommandPath)
    $sourceSha = Get-Sha256 -Path $source

    if (Test-Path -LiteralPath $destination -PathType Leaf) {
        $destinationSha = Get-Sha256 -Path $destination

        if ($destinationSha -ne $sourceSha) {
            throw (
                "Unified canonical launcher differs from the executing launcher: " +
                "$destination SourceSHA=$sourceSha DestinationSHA=$destinationSha"
            )
        }

        return $destination
    }

    Copy-Item -LiteralPath $source -Destination $destination

    if ((Get-Sha256 -Path $destination) -ne $sourceSha) {
        throw "Unified self-deployment SHA verification failed."
    }

    return $destination
}

