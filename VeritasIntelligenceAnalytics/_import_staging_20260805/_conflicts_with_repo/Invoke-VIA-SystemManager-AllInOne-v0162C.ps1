function Get-NowIso {
    return (Get-Date).ToString("o")
}

function Ensure-Directory {
    param(
        [Parameter(Mandatory)]
        [ValidateNotNullOrEmpty()]
        [string]$Path
    )

    if (-not (Test-Path -LiteralPath $Path -PathType Container)) {
        New-Item -ItemType Directory -Path $Path -Force | Out-Null
    }
}

function Get-Sha256 {
    param(
        [Parameter(Mandatory)]
        [ValidateNotNullOrEmpty()]
        [string]$Path
    )

    if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) {
        return ""
    }

    return (
        Get-FileHash -LiteralPath $Path -Algorithm SHA256
    ).Hash.ToLowerInvariant()
}

function Write-Utf8NoBomAtomic {
    param(
        [Parameter(Mandatory)][string]$Path,
        [Parameter(Mandatory)][AllowEmptyString()][string]$Text
    )

    $parent = Split-Path -Parent $Path

    if (-not [string]::IsNullOrWhiteSpace($parent)) {
        Ensure-Directory -Path $parent
    }

    $temporary = "{0}.tmp.{1}.{2}" -f
        $Path,
        $PID,
        ([DateTime]::UtcNow.Ticks)

    $encoding = [System.Text.UTF8Encoding]::new($false)

    [System.IO.File]::WriteAllText(
        $temporary,
        $Text,
        $encoding
    )

    [System.IO.File]::Move(
        $temporary,
        $Path,
        $true
    )
}

function Write-JsonAtomic {
    param(
        [Parameter(Mandatory)][string]$Path,
        [Parameter(Mandatory)]$Value
    )

    $json = (
        $Value |
        ConvertTo-Json -Depth 100
    ) + [Environment]::NewLine

    Write-Utf8NoBomAtomic -Path $Path -Text $json
}

function Read-JsonSafe {
    param(
        [Parameter(Mandatory)][string]$Path
    )

    if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) {
        return $null
    }

    try {
        return (
            Get-Content `
                -LiteralPath $Path `
                -Raw `
                -Encoding UTF8 |
            ConvertFrom-Json
        )
    }
    catch {
        return $null
    }
}

function Append-Utf8JsonLine {
    param(
        [Parameter(Mandatory)][string]$Path,
        [Parameter(Mandatory)]$Value
    )

    Ensure-Directory -Path (Split-Path -Parent $Path)

    $line = $Value | ConvertTo-Json -Depth 100 -Compress
    $encoding = [System.Text.UTF8Encoding]::new($false)
    $prefix = ""

    if (Test-Path -LiteralPath $Path -PathType Leaf) {
        $bytes = [System.IO.File]::ReadAllBytes($Path)

        if (
            $bytes.Length -gt 0 -and
            $bytes[$bytes.Length - 1] -ne 10
        ) {
            $prefix = [Environment]::NewLine
        }
    }

    [System.IO.File]::AppendAllText(
        $Path,
        $prefix + $line + [Environment]::NewLine,
        $encoding
    )
}

function Resolve-BaseRoot {
    param(
        [AllowEmptyString()][string]$Requested
    )

    $candidates = [System.Collections.Generic.List[string]]::new()

    foreach ($candidate in @(
        $Requested,
        $PSScriptRoot,
        (Get-Location).Path,
        "$env:USERPROFILE\Downloads\VeritasIntelligenceAnalytics",
        "$env:USERPROFILE\OneDrive\VeritasIntelligenceAnalytics",
        "$env:USERPROFILE\OneDrive\文件\VeritasIntelligenceAnalytics",
        "C:\VeritasIntelligenceAnalytics"
    )) {
        if (-not [string]::IsNullOrWhiteSpace($candidate)) {
            [void]$candidates.Add($candidate)
        }
    }

    $seen = @{}

    foreach ($candidate in $candidates) {
        try {
            $current = [System.IO.Path]::GetFullPath($candidate)
        }
        catch {
            continue
        }

        for ($depth = 0; $depth -le 8; $depth++) {
            $key = $current.ToLowerInvariant()

            if (-not $seen.ContainsKey($key)) {
                $seen[$key] = $true

                $supportive = Join-Path `
                    -Path $current `
                    -ChildPath "supportive modules"

                $functional = Join-Path `
                    -Path $current `
                    -ChildPath "functional modules"

                $module = Join-Path `
                    -Path $current `
                    -ChildPath "module"

                if (
                    (Test-Path -LiteralPath $supportive -PathType Container) -and
                    (
                        (Test-Path -LiteralPath $functional -PathType Container) -or
                        (Test-Path -LiteralPath $module -PathType Container)
                    )
                ) {
                    return $current
                }
            }

            $parent = Split-Path -Parent $current

            if (
                [string]::IsNullOrWhiteSpace($parent) -or
                $parent -eq $current
            ) {
                break
            }

            $current = $parent
        }
    }

    throw "Could not resolve the VIA mother-system Base."
}

