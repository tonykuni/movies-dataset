    )

    foreach ($candidate in @(
        (Join-Path -Path $BaseRoot -ChildPath "functional modules\VDF\input"),
        (Join-Path -Path $BaseRoot -ChildPath "functional modules\VDF\data"),
        (Join-Path -Path $BaseRoot -ChildPath "module\VeritasDataForge\data"),
        (Join-Path -Path $BaseRoot -ChildPath "_vdf_input")
    )) {
        if (Test-Path -LiteralPath $candidate -PathType Container) {
            return $candidate
        }
    }

    return Join-Path -Path $BaseRoot -ChildPath "_vdf_input"
}

function Write-MasterStatus {
    param(
        [Parameter(Mandatory)][string]$StatusPath,
        [Parameter(Mandatory)][string]$State,
        [Parameter(Mandatory)][int]$Percent,
        [Parameter(Mandatory)][string]$Narration,
        [AllowNull()]$Extra = $null
    )

    $payload = [ordered]@{
        version = $Script:Version
        updated_at = Get-NowIso
        state = $State
        percent = [math]::Max(0, [math]::Min(100, $Percent))
        narration = $Narration
        terminal = $State -in @("COMPLETED", "FAILED")
    }

    if ($null -ne $Extra) {
        foreach ($property in $Extra.PSObject.Properties) {
            $payload[$property.Name] = $property.Value
        }
    }

    Write-JsonAtomic -Path $StatusPath -Value $payload
}

function Start-ChildProcess {
    param(
        [Parameter(Mandatory)][string]$FilePath,
        [Parameter(Mandatory)][string[]]$ArgumentList,
        [Parameter(Mandatory)][string]$WorkingDirectory,
        [Parameter(Mandatory)][string]$StdoutPath,
        [Parameter(Mandatory)][string]$StderrPath
    )

    Ensure-Directory -Path (Split-Path -Parent $StdoutPath)
    Ensure-Directory -Path (Split-Path -Parent $StderrPath)

    return Start-Process `
        -FilePath $FilePath `
        -ArgumentList $ArgumentList `
        -WorkingDirectory $WorkingDirectory `
        -RedirectStandardOutput $StdoutPath `
        -RedirectStandardError $StderrPath `
        -PassThru
}

function Get-LogTail {
    param(
        [AllowEmptyString()][string]$Path,
        [int]$LineCount = 80
    )

    if (
        [string]::IsNullOrWhiteSpace($Path) -or
        -not (
            Test-Path `
                -LiteralPath $Path `
                -PathType Leaf
        )
    ) {
        return ""
    }

    try {
        return (
            Get-Content `
                -LiteralPath $Path `
                -Tail $LineCount `
                -Encoding UTF8 `
                -ErrorAction Stop
        ) -join [Environment]::NewLine
    }
    catch {
        return (
            "LOG_READ_FAILED: " +
            $_.Exception.Message
        )
    }
}

function Add-WorkerStatusExtras {
    param(
        [Parameter(Mandatory)][string]$WorkerKey,
        [Parameter(Mandatory)]$Status,
        [Parameter(Mandatory)][System.Collections.IDictionary]$Extra
    )

    if ($WorkerKey -eq "UNIFIED") {
        foreach ($Name in @(
            "gate",
            "current_round",
            "matrix_report",
            "round_reports",
            "summary",
            "hydra_count",
            "ssot_group_count",
            "repair_candidate_count",
            "library_registry",
            "function_registry",
            "supportive_registry",
            "ssot_registry",
            "deployment_manifest",
            "subsystems"
        )) {
            if ($null -ne $Status.PSObject.Properties[$Name]) {
                $Extra[$Name] = $Status.$Name
            }
        }

        return
    }

    if ($WorkerKey -eq "VRN") {
        if ($null -ne $Status.PSObject.Properties["v0156_gate"]) {
            $Extra["vrn_gate"] = $Status.v0156_gate
        }

        if ($null -ne $Status.PSObject.Properties["v0156_report"]) {
            $Extra["vrn_report"] = $Status.v0156_report
        }

        foreach ($Name in @(
            "basic_info_page",
            "financial_data_page",
            "v0156_evidence_mode",
            "v0156_summary",
            "launcher_console"
        )) {
            if ($null -ne $Status.PSObject.Properties[$Name]) {
                $Extra[$Name] = $Status.$Name
            }
        }

        return
    }

    if ($WorkerKey -eq "VDF") {
        if ($null -ne $Status.PSObject.Properties["gate"]) {
            $Extra["vdf_gate"] = $Status.gate
        }

        foreach ($Name in @(
            "basic_info_page",
            "financial_data_page",
            "market_data_page",
            "data_quality_page",
            "output_inventory"
        )) {
            if ($null -ne $Status.PSObject.Properties[$Name]) {
                $Extra[$Name] = $Status.$Name
            }
        }
    }
}

function Invoke-WorkerMode {
    param(
        [Parameter(Mandatory)][string]$ConfigPath
    )

    $config = Get-Content `
        -LiteralPath $ConfigPath `
        -Raw `
        -Encoding UTF8 |
        ConvertFrom-Json

    $baseRoot = Resolve-BaseRoot -Requested ([string]$config.base)
    $runtime = Deploy-UnifiedRuntime -BaseRoot $baseRoot
    $python = Resolve-PythonRuntime -BaseRoot $baseRoot

    $pwsh = (Get-Process -Id $PID).Path
    $runDir = [string]$config.run_dir
    $statusPath = [string]$config.status_path
    $action = ([string]$config.action).ToUpperInvariant()

    foreach ($folder in @(
        $runDir,
        (Join-Path -Path $runDir -ChildPath "logs"),
        (Join-Path -Path $runDir -ChildPath "configs"),
        (Join-Path -Path $runDir -ChildPath "status")
    )) {
        Ensure-Directory -Path $folder
    }

    Write-MasterStatus `
        -StatusPath $statusPath `
        -State "RUNNING" `
        -Percent 1 `
        -Narration "Runtime deployed. Initializing selected non-blocking workers." `
        -Extra ([pscustomobject]@{
            run_dir = $runDir
            runtime_root = $runtime.runtime_root
            runtime_registry = $runtime.registry
            runtime_snapshot = $runtime.snapshot
        })

    $workers = @()

    if ($action -in @("UNIFIED", "ALL")) {
        $unifiedStatus = Join-Path -Path $runDir -ChildPath "status\unified.json"
        $unifiedConfig = Join-Path -Path $runDir -ChildPath "configs\unified.json"

        Write-JsonAtomic `
            -Path $unifiedConfig `
            -Value ([ordered]@{
                version = $Script:Version
                base = $baseRoot
                run_dir = (Join-Path -Path $runDir -ChildPath "UNIFIED_ANALYSIS")
                status_path = $unifiedStatus
                pwsh_path = $pwsh
                auto_fix = [bool]$config.auto_fix
            })

        $process = Start-ChildProcess `
            -FilePath $python `
            -ArgumentList @(
                ('"{0}"' -f $runtime.engine),
                "--config",
                ('"{0}"' -f $unifiedConfig)
            ) `
            -WorkingDirectory $runtime.runtime_root `
            -StdoutPath (Join-Path -Path $runDir -ChildPath "logs\unified.stdout.log") `
            -StderrPath (Join-Path -Path $runDir -ChildPath "logs\unified.stderr.log")

        $workers += [pscustomobject]@{
            key = "UNIFIED"
            status = $unifiedStatus
            process = $process
            stdout = (Join-Path -Path $runDir -ChildPath "logs\unified.stdout.log")
            stderr = (Join-Path -Path $runDir -ChildPath "logs\unified.stderr.log")
        }
    }

    if ($action -in @("VRN", "ALL")) {
        $vrnStatus = Join-Path -Path $runDir -ChildPath "status\vrn.json"
        $vrnConfig = Join-Path -Path $runDir -ChildPath "configs\vrn.json"

        $vrnPython = [string]$config.vrn.python

        if ([string]::IsNullOrWhiteSpace($vrnPython)) {
            $vrnPython = $python
        }

        Write-JsonAtomic `
            -Path $vrnConfig `
            -Value ([ordered]@{
                version = "v0159"
                statusPath = $vrnStatus
                runDir = (Join-Path -Path $runDir -ChildPath "VRN")
                parameters = [ordered]@{
                    base = $baseRoot
                    input = [string]$config.vrn.input
                    manifest = [string]$config.vrn.manifest
                    python = $vrnPython
                    timeout = [int]$config.vrn.timeout
                    recursive = [bool]$config.vrn.recursive
                    openHtml = $false
                }
                sources = @($config.vrn.sources)
            })

        $process = Start-ChildProcess `
            -FilePath $pwsh `
            -ArgumentList @(
                "-NoLogo",
                "-NoProfile",
                "-ExecutionPolicy",
                "Bypass",
                "-File",
                ('"{0}"' -f $runtime.vrn),
                "-Worker",
                "-WorkerConfig",
                ('"{0}"' -f $vrnConfig)
            ) `
            -WorkingDirectory $runtime.runtime_root `
            -StdoutPath (Join-Path -Path $runDir -ChildPath "logs\vrn.stdout.log") `
            -StderrPath (Join-Path -Path $runDir -ChildPath "logs\vrn.stderr.log")

        $workers += [pscustomobject]@{
            key = "VRN"
            status = $vrnStatus
            process = $process
            stdout = (Join-Path -Path $runDir -ChildPath "logs\vrn.stdout.log")
            stderr = (Join-Path -Path $runDir -ChildPath "logs\vrn.stderr.log")
        }
    }

    if ($action -in @("VDF", "ALL")) {
        $vdfStatus = Join-Path -Path $runDir -ChildPath "status\vdf.json"
        $vdfConfig = Join-Path -Path $runDir -ChildPath "configs\vdf.json"

        Write-JsonAtomic `
            -Path $vdfConfig `
            -Value ([ordered]@{
                version = "v0160A"
                statusPath = $vdfStatus
                runDir = (Join-Path -Path $runDir -ChildPath "VDF")
                parameters = [ordered]@{
                    base = $baseRoot
                    input = [string]$config.vdf.input
                    startDate = [string]$config.vdf.startDate
                    endDate = [string]$config.vdf.endDate
                    universe = [string]$config.vdf.universe
                    updateMode = [string]$config.vdf.updateMode
                    openHtml = $false
                    recursive = [bool]$config.vdf.recursive
                    timeoutSeconds = [int]$config.vdf.timeoutSeconds
                }
                sources = @($config.vdf.sources)
            })

        $process = Start-ChildProcess `
            -FilePath $pwsh `
            -ArgumentList @(
                "-NoLogo",
                "-NoProfile",
                "-ExecutionPolicy",
                "Bypass",
                "-File",
                ('"{0}"' -f $runtime.vdf),
                "-Worker",
                "-WorkerConfig",
                ('"{0}"' -f $vdfConfig)
            ) `
            -WorkingDirectory $runtime.runtime_root `
            -StdoutPath (Join-Path -Path $runDir -ChildPath "logs\vdf.stdout.log") `
            -StderrPath (Join-Path -Path $runDir -ChildPath "logs\vdf.stderr.log")

        $workers += [pscustomobject]@{
            key = "VDF"
            status = $vdfStatus
            process = $process
            stdout = (Join-Path -Path $runDir -ChildPath "logs\vdf.stdout.log")
            stderr = (Join-Path -Path $runDir -ChildPath "logs\vdf.stderr.log")
        }
    }

    if ($workers.Count -eq 0) {
        throw "No worker was selected for action: $action"
    }

    $started = Get-Date
    $timeoutSeconds = [math]::Max(
        [int]$config.vrn.timeout,
        [int]$config.vdf.timeoutSeconds
    ) + 900

    while ($true) {
        $terminalCount = 0
        $progressValues = @()
        $stateValues = @()
        $narrations = @()
        $failedWorkers = @()
        $workerExitCodes = [ordered]@{}
        $workerDiagnostics = [ordered]@{}

        $extra = [ordered]@{
            run_dir = $runDir
            runtime_root = $runtime.runtime_root
            runtime_registry = $runtime.registry
            action = $action
        }

        foreach ($workerItem in $workers) {
            $workerItem.process.Refresh()

            $status =
                Read-JsonSafe `
                    -Path ([string]$workerItem.status)

            $hasExited =
                [bool]$workerItem.process.HasExited

            $statusTerminal = $false

            if (
                $null -ne $status -and
                $null -ne $status.PSObject.Properties["terminal"]
            ) {
                $statusTerminal =
                    [bool]$status.terminal
            }

            if (
                $null -ne $status -and
                $statusTerminal
            ) {
                $terminalCount++
                $progressValues += [int]$status.percent
                $stateValues += [string]$status.state

                $workerNarration = ""

                if (
                    $null -ne $status.PSObject.Properties["narration"] -and
                    -not [string]::IsNullOrWhiteSpace(
                        [string]$status.narration
                    )
                ) {
                    $workerNarration =
                        [string]$status.narration
                }
                elseif (
                    $null -ne $status.PSObject.Properties["message"] -and
                    -not [string]::IsNullOrWhiteSpace(
                        [string]$status.message
                    )
                ) {
                    $workerNarration =
                        [string]$status.message
                }
                else {
                    $workerNarration =
                        [string]$status.state
                }

                $narrations += (
                    "{0}: {1}" -f
                    $workerItem.key,
                    $workerNarration
                )

                if (
                    [string]$status.state -eq "FAILED"
                ) {
                    $failedWorkers +=
                        [string]$workerItem.key
                }

                Add-WorkerStatusExtras `
                    -WorkerKey ([string]$workerItem.key) `
                    -Status $status `
                    -Extra $extra

                continue
            }

            if ($hasExited) {
                $exitCode =
                    [int]$workerItem.process.ExitCode

                $stderrTail =
                    Get-LogTail `
                        -Path ([string]$workerItem.stderr) `
                        -LineCount 100

                $stdoutTail =
                    Get-LogTail `
                        -Path ([string]$workerItem.stdout) `
                        -LineCount 60

                $diagnosticParts = @(
                    "ExitCode=$exitCode"
                )

                if (
                    -not [string]::IsNullOrWhiteSpace(
                        $stderrTail
                    )
                ) {
                    $diagnosticParts += (
                        "STDERR:`n" +
                        $stderrTail
                    )
                }

                if (
                    -not [string]::IsNullOrWhiteSpace(
                        $stdoutTail
                    )
                ) {
                    $diagnosticParts += (
                        "STDOUT:`n" +
                        $stdoutTail
                    )
                }

                $diagnostic =
                    $diagnosticParts -join
                    [Environment]::NewLine

                $message = (
                    "{0} exited before writing a terminal status. " +
                    "ExitCode={1}. Inspect {2} and {3}." -f
                    $workerItem.key,
                    $exitCode,
                    $workerItem.stderr,
                    $workerItem.stdout
                )

                Write-MasterStatus `
                    -StatusPath ([string]$workerItem.status) `
                    -State "FAILED" `
                    -Percent 100 `
                    -Narration $message `
                    -Extra ([pscustomobject]@{
                        gate = (
                            "{0}_PROCESS_EXIT_NO_STATUS" -f
                            $workerItem.key
                        )
                        exit_code = $exitCode
                        stderr_path =
                            [string]$workerItem.stderr
                        stdout_path =
                            [string]$workerItem.stdout
                        diagnostic = $diagnostic
                    })

                $terminalCount++
                $progressValues += 100
                $stateValues += "FAILED"
                $failedWorkers +=
                    [string]$workerItem.key

                $workerExitCodes[
                    [string]$workerItem.key
                ] = $exitCode

                $workerDiagnostics[
                    [string]$workerItem.key
                ] = $diagnostic

                $narrations += (
                    "{0}: {1}" -f
                    $workerItem.key,
                    $message
                )

                continue
            }

            if ($null -ne $status) {
                $progressValues +=
                    [int]$status.percent

                $stateValues +=
                    [string]$status.state

                $workerNarration = ""

                if (
                    $null -ne $status.PSObject.Properties["narration"] -and
                    -not [string]::IsNullOrWhiteSpace(
                        [string]$status.narration
                    )
                ) {
                    $workerNarration =
                        [string]$status.narration
                }
                elseif (
                    $null -ne $status.PSObject.Properties["message"] -and
                    -not [string]::IsNullOrWhiteSpace(
                        [string]$status.message
                    )
                ) {
                    $workerNarration =
                        [string]$status.message
                }
                else {
                    $workerNarration =
                        [string]$status.state
                }

                $narrations += (
                    "{0}: {1}" -f
                    $workerItem.key,
                    $workerNarration
                )

                Add-WorkerStatusExtras `
                    -WorkerKey ([string]$workerItem.key) `
                    -Status $status `
                    -Extra $extra
            }
            else {
                $progressValues += 1
                $stateValues += "RUNNING"
                $narrations += (
                    "{0}: initializing." -f
                    $workerItem.key
                )
            }
        }

        if (@($failedWorkers).Count -gt 0) {
            $extra["failed_workers"] = @(
                $failedWorkers |
                Sort-Object -Unique
            )
        }

        if ($workerExitCodes.Count -gt 0) {
            $extra["worker_exit_codes"] =
                $workerExitCodes
        }

        if ($workerDiagnostics.Count -gt 0) {
            $extra["worker_diagnostics"] =
                $workerDiagnostics
        }

        $average = [int][math]::Round(
            (
                $progressValues |
                Measure-Object -Average
            ).Average
        )

        $allTerminal =
            $terminalCount -eq $workers.Count

        $mergedState = if ($allTerminal) {
            if ($stateValues -contains "FAILED") {
                "FAILED"
            }
            else {
                "COMPLETED"
            }
        }
        else {
            "RUNNING"
        }

        $mergedGateParts = @()

        foreach ($key in @("gate", "vrn_gate", "vdf_gate")) {
            if (
                $extra.Contains($key) -and
                -not [string]::IsNullOrWhiteSpace([string]$extra[$key])
            ) {
                $mergedGateParts += [string]$extra[$key]
            }
        }

        if ($mergedGateParts.Count -gt 0) {
            $extra["gate"] = $mergedGateParts -join " | "
        }

        $mergedPercent = $average

        if ($mergedState -in @("COMPLETED", "FAILED")) {
            $mergedPercent = 100
        }

        Write-MasterStatus `
            -StatusPath $statusPath `
            -State $mergedState `
            -Percent $mergedPercent `
            -Narration ($narrations -join " || ") `
            -Extra ([pscustomobject]$extra)

        if ($allTerminal) {
            break
        }

        if (((Get-Date) - $started).TotalSeconds -ge $timeoutSeconds) {
            Write-MasterStatus `
                -StatusPath $statusPath `
                -State "FAILED" `
                -Percent 100 `
                -Narration (
                    "Unified timeout reached. Child processes were not forcibly terminated."
                ) `
                -Extra ([pscustomobject]@{
                    run_dir = $runDir
                    error_message = "TIMEOUT_CHILDREN_LEFT_RUNNING"
                    gate = "UNIFIED_TIMEOUT_FAIL_CLOSED"
                })

            break
        }

        Start-Sleep -Milliseconds 700
    }
}


function Install-SystemManagerEntrypoints {
    param(
        [Parameter(Mandatory)][string]$BaseRoot,
        [Parameter(Mandatory)][string]$CanonicalMaster,
        [Parameter(Mandatory)][string]$RuntimeRoot
    )

    $canonicalSha =
        Get-Sha256 -Path $CanonicalMaster

    if ([string]::IsNullOrWhiteSpace($canonicalSha)) {
        throw "Canonical System Manager SHA256 could not be calculated."
    }

    $downloads = Join-Path `
        -Path $env:USERPROFILE `
        -ChildPath "Downloads"

    Ensure-Directory -Path $downloads

    $dailyPath = Join-Path `
        -Path $downloads `
        -ChildPath "Start-VIA-SystemManager.ps1"

    $compatibilityPath = Join-Path `
        -Path $downloads `
        -ChildPath "Start-VIA-Unified.ps1"

    $canonicalLiteral =
        "'" +
        ([string]$CanonicalMaster).Replace(
            "'",
            "''"
        ) +
        "'"

    $shaLiteral =
        "'" +
        ([string]$canonicalSha).Replace(
            "'",
            "''"
        ) +
        "'"

    $baseLiteral =
        "'" +
        ([string]$BaseRoot).Replace(
            "'",
            "''"
        ) +
        "'"

    $dailyTemplate = @'
#requires -Version 7.0
Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

$Launcher = __VIA_CANONICAL_LITERAL__
$ExpectedSHA = __VIA_SHA_LITERAL__
$Base = __VIA_BASE_LITERAL__

if (-not (
    Test-Path `
        -LiteralPath $Launcher `
        -PathType Leaf
)) {
    throw (
        "VIA System Manager canonical launcher is missing: " +
        $Launcher
    )
}

$ActualSHA = (
    Get-FileHash `
        -LiteralPath $Launcher `
        -Algorithm SHA256
).Hash.ToLowerInvariant()

if ($ActualSHA -ne $ExpectedSHA) {
    throw (
        "VIA System Manager canonical SHA256 mismatch. " +
        "Expected=$ExpectedSHA Actual=$ActualSHA"
    )
}

$Tokens = $null
$Errors = $null

[System.Management.Automation.Language.Parser]::ParseFile(
    $Launcher,
    [ref]$Tokens,
    [ref]$Errors
) | Out-Null

if (@($Errors).Count -gt 0) {
    Write-Host ""
    Write-Host (
        "def CANONICAL AST : FAIL"
    ) -ForegroundColor Red

    foreach ($ParseError in @($Errors)) {
        Write-Host (
            "Line {0}, Column {1}: {2}" -f
            $ParseError.Extent.StartLineNumber,
            $ParseError.Extent.StartColumnNumber,
            $ParseError.Message
        ) -ForegroundColor Red
    }

    throw (
        "VIA System Manager canonical AST validation failed."
    )
}

& $Launcher -Base $Base
'@

    $dailyText =
        $dailyTemplate.
            Replace(
                "__VIA_CANONICAL_LITERAL__",
                $canonicalLiteral
            ).
            Replace(
                "__VIA_SHA_LITERAL__",
                $shaLiteral
            ).
            Replace(
                "__VIA_BASE_LITERAL__",
                $baseLiteral
            )

    Write-Utf8NoBomAtomic `
        -Path $dailyPath `
        -Text $dailyText

    Write-Utf8NoBomAtomic `
        -Path $compatibilityPath `
        -Text $dailyText

    foreach ($launcherPath in @(
        $dailyPath,
        $compatibilityPath
    )) {
        $tokens = $null
        $errors = $null

        [System.Management.Automation.Language.Parser]::ParseFile(
            $launcherPath,
            [ref]$tokens,
            [ref]$errors
        ) | Out-Null

        if (@($errors).Count -gt 0) {
            Write-Host ""
            Write-Host (
                "def GENERATED DAILY LAUNCHER AST : FAIL"
            ) -ForegroundColor Red

            Write-Host (
                "def Launcher : {0}" -f
                $launcherPath
            ) -ForegroundColor Red

            foreach ($ParseError in @($errors)) {
                Write-Host (
                    "Line {0}, Column {1}: {2}" -f
                    $ParseError.Extent.StartLineNumber,
                    $ParseError.Extent.StartColumnNumber,
                    $ParseError.Message
                ) -ForegroundColor Red
            }

            throw (
                "Generated daily launcher AST validation failed: " +
                $launcherPath
            )
        }
    }

    $desktop =
        [Environment]::GetFolderPath("Desktop")

    $shortcutPath = ""

    if (-not [string]::IsNullOrWhiteSpace($desktop)) {
        $shortcutPath = Join-Path `
            -Path $desktop `
            -ChildPath "VIA System Manager v0162C.lnk"

        $pwsh =
            (Get-Process -Id $PID).Path

        $shell =
            New-Object -ComObject WScript.Shell

        try {
            $shortcut =
                $shell.CreateShortcut($shortcutPath)

            $shortcut.TargetPath = $pwsh
            $shortcut.Arguments = (
                '-NoLogo -NoProfile ' +
                '-ExecutionPolicy Bypass ' +
                '-File "{0}"' -f
                $dailyPath
            )
            $shortcut.WorkingDirectory = $BaseRoot
            $shortcut.IconLocation = "$pwsh,0"
            $shortcut.Description =
                "VIA System Manager v0162C · Auto Launch All"
            $shortcut.Save()
        }
        finally {
            if ($null -ne $shell) {
                [void][System.Runtime.InteropServices.Marshal]::ReleaseComObject(
                    $shell
                )
            }
        }
    }

    $registryRoot = Join-Path `
        -Path $RuntimeRoot `
        -ChildPath "registry"

    Ensure-Directory -Path $registryRoot

    $ledgerPath = Join-Path `
        -Path $registryRoot `
        -ChildPath "VIA_SystemManager_Entrypoint_Registry.v0162C.jsonl"

    $event = [ordered]@{
        event = "VIA_SYSTEM_MANAGER_ENTRYPOINTS_READY"
        recorded_at = Get-NowIso
        version = $Script:Version
        base = $BaseRoot
        canonical = $CanonicalMaster
        canonical_sha256 = $canonicalSha
        daily_launcher = $dailyPath
        compatibility_launcher = $compatibilityPath
        desktop_shortcut = $shortcutPath
        default_mode = "AUTO_LAUNCH_ALL"
        ui_only_switch = "-UiOnly"
        canonical_project_mutation = $false
    }

    $line =
        $event |
        ConvertTo-Json -Depth 30 -Compress

    [System.IO.File]::AppendAllText(
        $ledgerPath,
        $line + [Environment]::NewLine,
        [System.Text.UTF8Encoding]::new($false)
    )

    return [pscustomobject]@{
        daily = $dailyPath
        compatibility = $compatibilityPath
        shortcut = $shortcutPath
        ledger = $ledgerPath
        canonical_sha256 = $canonicalSha
    }
}

function Start-UnifiedUi {
    param(
        [AllowEmptyString()][string]$RequestedBase,
        [switch]$AutoLaunchAll
    )

    $baseRoot = Resolve-BaseRoot -Requested $RequestedBase
    $runtime = Deploy-UnifiedRuntime -BaseRoot $baseRoot
    $python = Resolve-PythonRuntime -BaseRoot $baseRoot

    $entrypoints =
        Install-SystemManagerEntrypoints `
            -BaseRoot $baseRoot `
            -CanonicalMaster ([string]$runtime.master) `
            -RuntimeRoot ([string]$runtime.runtime_root)

    if ($null -eq $entrypoints) {
        throw "System Manager entrypoint installation returned no result."
    }

    $dailyPath = [string]$entrypoints.daily
    $compatibilityPath = [string]$entrypoints.compatibility
    $shortcutPath = [string]$entrypoints.shortcut
    $entrypointLedger = [string]$entrypoints.ledger

    if ([string]::IsNullOrWhiteSpace($dailyPath)) {
        throw "System Manager daily launcher was not created."
    }

    if (-not (Test-Path -LiteralPath $dailyPath -PathType Leaf)) {
        throw ("System Manager daily launcher is missing after creation: " + $dailyPath)
    }

    if ([string]::IsNullOrWhiteSpace($compatibilityPath)) {
        throw "Compatibility launcher path was not returned."
    }

    if (-not (Test-Path -LiteralPath $compatibilityPath -PathType Leaf)) {
        throw ("Compatibility launcher is missing after creation: " + $compatibilityPath)
    }

    $sessionId = "VIAUNI_{0}_{1}" -f
        (Get-Date -Format "yyyyMMdd_HHmmss"),
        ([guid]::NewGuid().ToString("N").Substring(0, 8))

    $sessionRoot = Join-Path `
        -Path $env:TEMP `
        -ChildPath "VIA_UNIFIED_UI\$sessionId"

    Ensure-Directory -Path $sessionRoot

    $htaPath = Join-Path `
        -Path $sessionRoot `
        -ChildPath "VIA_Unified_Workbench_v0162C.hta"

    $dialogPath = Join-Path `
        -Path $sessionRoot `
        -ChildPath "VIA_Unified_WindowsDialog_v0162C.ps1"

    Copy-Item -LiteralPath $runtime.hta -Destination $htaPath
    Copy-Item -LiteralPath $runtime.dialog -Destination $dialogPath

    $contextPath = Join-Path `
        -Path $sessionRoot `
        -ChildPath "ui_context.json"

    $workerConfig = Join-Path `
        -Path $sessionRoot `
        -ChildPath "worker_config.json"

    $statusPath = Join-Path `
        -Path $sessionRoot `
        -ChildPath "worker_status.json"

    $vrnInput = Join-Path `
        -Path $baseRoot `
        -ChildPath "_vrn_research_report_incremental_intake_v0156\incoming"

    $vrnManifest = Join-Path `
        -Path $baseRoot `
        -ChildPath "_vrn_research_report_incremental_intake_v0156\VRN_ResearchReport_Incremental_Manifest.v0156.jsonl"

    $vdfInput = Resolve-VdfInput -BaseRoot $baseRoot

    Write-JsonAtomic `
        -Path $contextPath `
        -Value ([ordered]@{
            version = $Script:Version
            base = $baseRoot
            python = $python
            runtime_root = $runtime.runtime_root
            runtime_registry = $runtime.registry
            master_script = $runtime.master
            pwsh_path = (Get-Process -Id $PID).Path
            dialog_helper = $dialogPath
            session_root = $sessionRoot
            worker_config = $workerConfig
            status_path = $statusPath
            auto_launch_all = [bool]$AutoLaunchAll
            entrypoints = [ordered]@{
                daily = $dailyPath
                compatibility = $compatibilityPath
                shortcut = $shortcutPath
                ledger = $entrypointLedger
            }
            defaults = [ordered]@{
                vrn_input = $vrnInput
                vrn_manifest = $vrnManifest
                vdf_input = $vdfInput
                start_date = (Get-Date -Format "yyyy-MM-dd")
            }
        })

    $mshta = Join-Path `
        -Path $env:WINDIR `
        -ChildPath "System32\mshta.exe"

    if (-not (Test-Path -LiteralPath $mshta -PathType Leaf)) {
        throw "Windows mshta.exe is unavailable or disabled."
    }

    Write-Host ""
    Write-Host ("=" * 120) -ForegroundColor DarkCyan
    Write-Host ("def VIA · SYSTEM MANAGER ALL-IN-ONE · {0}" -f $Script:Version) -ForegroundColor Cyan
    Write-Host ("def Base       : {0}" -f $baseRoot) -ForegroundColor White
    Write-Host ("def Runtime    : {0}" -f $runtime.runtime_root) -ForegroundColor White
    Write-Host ("def Python     : {0}" -f $python) -ForegroundColor White
    Write-Host ("def HTML U/I   : {0}" -f $htaPath) -ForegroundColor Cyan
    Write-Host ("def Daily      : {0}" -f $dailyPath) -ForegroundColor White
    Write-Host ("def Shortcut   : {0}" -f $shortcutPath) -ForegroundColor White
    Write-Host (
        "def Start Mode : {0}" -f
        $(if ($AutoLaunchAll) { "AUTO_LAUNCH_ALL" } else { "UI_ONLY" })
    ) -ForegroundColor Green
    Write-Host "def Accelerators: 20 ENABLED" -ForegroundColor Green
    Write-Host "def Repair      : SANDBOX ONLY" -ForegroundColor Yellow
    Write-Host "def Canonical   : NO MUTATION" -ForegroundColor Yellow
    Write-Host ("=" * 120) -ForegroundColor DarkCyan

    $uiProcess =
        Start-Process `
            -FilePath $mshta `
            -ArgumentList ('"{0}"' -f $htaPath) `
            -PassThru

    Write-Host (
        "def UI Process  : PID {0} · NON_BLOCKING" -f
        $uiProcess.Id
    ) -ForegroundColor Green
}

if ($Worker) {
    if ([string]::IsNullOrWhiteSpace($WorkerConfig)) {
        throw "-WorkerConfig is required in Worker mode."
    }

    try {
        Invoke-WorkerMode -ConfigPath $WorkerConfig
    }
    catch {
        $config = Read-JsonSafe -Path $WorkerConfig
        $statusPath = if (
            $null -ne $config -and
            $null -ne $config.PSObject.Properties["status_path"]
        ) {
            [string]$config.status_path
        }
        else {
            Join-Path -Path (Split-Path -Parent $WorkerConfig) -ChildPath "worker_status.json"
        }

        Write-MasterStatus `
            -StatusPath $statusPath `
            -State "FAILED" `
            -Percent 100 `
            -Narration $_.Exception.Message `
            -Extra ([pscustomobject]@{
                error_type = $_.Exception.GetType().FullName
                error_message = $_.Exception.Message
                stack_trace = $_.ScriptStackTrace
                gate = "UNIFIED_WORKER_FAIL_CLOSED"
            })

        exit 3
    }

    exit 0
}

try {
    Start-UnifiedUi `
        -RequestedBase $Base `
        -AutoLaunchAll:(-not $UiOnly)
}
catch {
    Write-Host ""
    Write-Host "def VIA · SYSTEM MANAGER SAFE CATCH" -ForegroundColor Red
    Write-Host ("def ErrorType    : {0}" -f $_.Exception.GetType().FullName) -ForegroundColor Red
    Write-Host ("def ErrorMessage : {0}" -f $_.Exception.Message) -ForegroundColor Red
    Write-Host ("def StackTrace   : {0}" -f $_.ScriptStackTrace) -ForegroundColor DarkRed
}
finally {
    Write-Host ""
    Write-Host "def Parent PowerShell remains open." -ForegroundColor Cyan
}
